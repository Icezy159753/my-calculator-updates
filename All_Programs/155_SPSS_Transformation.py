    def _draft_job(self) -> TransformJob:
        if self.dataframe is None:
            raise ValueError("กรุณาเปิดไฟล์ SPSS ก่อน")
        columns = self.selected_columns()
        if not columns:
            raise ValueError("กรุณาเลือกตัวแปรต้นทางอย่างน้อย 1 ตัวแปร")
        existing_names = [*self.dataframe.columns, *(job.new_name for job in self.jobs)]
        name = validate_new_variable_name(self.name_input.text(), existing_names)
        if self._is_stacking():
            self._validated_index_name(extra_names=[name])
        if self._is_stacking() and self.jobs:
            # Counts may differ now: a shorter set is padded with empty blocks.
            used_sources = {
                source for job in self.jobs for source in job.source_columns
            }
            duplicates = [source for source in columns if source in used_sources]
            if duplicates:
                raise ValueError(
                    "ตัวแปรเหล่านี้ถูกใช้ในรายการอื่นแล้ว: " + ", ".join(duplicates)
                )
        return TransformJob(
            tuple(columns), name, self.var_label_input.text().strip()
        )

