class PastelSelectionDelegate(QStyledItemDelegate):
    """Force readable pastel hover/selection colors across Windows themes."""

    @staticmethod
    def _background_color(index) -> QColor | None:
        value = index.data(Qt.ItemDataRole.BackgroundRole)
        if isinstance(value, QBrush):
            return value.color()
        if isinstance(value, QColor):
            return value
        return None

    def _is_selected(self, option, index) -> bool:
        """A row we painted mint ourselves counts as selected, too.

        The queued-job table runs with SelectionMode.NoSelection, so its state
        lives in the item background instead of Qt's selection model.
        """
        if option.state & QStyle.StateFlag.State_Selected:
            return True
        background = self._background_color(index)
        return background is not None and background == QColor(SELECTED_BG)

    def _is_hovered(self, option, index) -> bool:
        """Hover the whole row, not just the cell under the cursor."""
        hover_row = getattr(self.parent(), "hover_row", None)
        if hover_row is not None:
            return hover_row == index.row()
        return bool(option.state & QStyle.StateFlag.State_MouseOver)

    def _paint_band(self, painter, option, index, background, foreground) -> None:
        painter.save()
        painter.fillRect(option.rect, QColor(background))
        painter.setPen(QColor(foreground))
        painter.setFont(option.font)
        painter.drawText(
            option.rect.adjusted(10, 0, -8, 0),
            Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter,
            str(index.data(Qt.ItemDataRole.DisplayRole) or ""),
        )
        painter.restore()

    def paint(self, painter, option, index) -> None:
        # Selection wins over hover: moving the mouse across the chosen row
        # must never repaint part of it in the hover color.
        if self._is_selected(option, index):
            self._paint_band(painter, option, index, SELECTED_BG, SELECTED_FG)
            return
        if self._is_hovered(option, index):
            self._paint_band(painter, option, index, HOVER_BG, HOVER_FG)
            return
        super().paint(painter, QStyleOptionViewItem(option), index)


class ComboItemDelegate(QStyledItemDelegate):
    """Two-tone rows for combo pop-ups: the choice, then its explanation.

    'ต่อแนวตั้ง (VARSTOCASES) — จำนวนเคสเพิ่ม' reads as one grey blob otherwise;
    splitting it lets the choice carry the weight and the note stay quiet.
    """

    ROW_HEIGHT = 42

    @staticmethod
    def split_text(text: str) -> tuple[str, str]:
        for separator in (" — ", " – ", " - "):
            if separator in text:
                head, tail = text.split(separator, 1)
                return head.strip(), tail.strip()
        if " (" in text and text.rstrip().endswith(")"):
            head, tail = text.split(" (", 1)
            return head.strip(), tail.rstrip(")").strip()
        return text.strip(), ""

    def sizeHint(self, option, index):
        size = super().sizeHint(option, index)
        size.setHeight(self.ROW_HEIGHT)
        return size

    def _chosen_row(self) -> int:
        """The value the combo actually holds — hovering must not move it."""
        combo = self.parent()
        return combo.currentIndex() if isinstance(combo, QComboBox) else -1

    def paint(self, painter, option, index) -> None:
        selected = bool(option.state & QStyle.StateFlag.State_Selected)
        hovered = bool(option.state & QStyle.StateFlag.State_MouseOver)
        painter.save()
        painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)

        body = QRectF(option.rect).adjusted(4, 3, -4, -3)
        if selected or hovered:
            painter.setPen(Qt.PenStyle.NoPen)
            painter.setBrush(QColor(SELECTED_BG if selected else HOVER_BG))
            painter.drawRoundedRect(body, 8, 8)

        head, tail = self.split_text(str(index.data(Qt.ItemDataRole.DisplayRole) or ""))
        text_area = body.adjusted(12, 0, -34, 0)

        head_font = QFont(option.font)
        head_font.setBold(True)
        painter.setFont(head_font)
        head_width = QFontMetrics(head_font).horizontalAdvance(head)
        painter.setPen(QColor(SELECTED_FG if selected else "#22314a"))
        painter.drawText(
            text_area,
            Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter,
            head,
        )

        if tail:
            tail_font = QFont(option.font)
            tail_font.setPointSizeF(max(option.font.pointSizeF() - 0.5, 7.5))
            painter.setFont(tail_font)
            metrics = QFontMetrics(tail_font)
            tail_area = text_area.adjusted(head_width + 10, 0, 0, 0)
            painter.setPen(QColor("#3f6f64" if selected else "#6a7b8f"))
            painter.drawText(
                tail_area,
                Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter,
                metrics.elidedText(
                    tail, Qt.TextElideMode.ElideRight, int(tail_area.width())
                ),
            )

        if index.row() == self._chosen_row():  # a quiet tick on the current value
            pen = QPen(QColor(SELECTED_FG if selected else "#1b9c85"), 2.0)
            pen.setCapStyle(Qt.PenCapStyle.RoundCap)
            pen.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
            painter.setPen(pen)
            painter.setBrush(Qt.BrushStyle.NoBrush)
            center_y = body.center().y()
            right = body.right() - 14
            check = QPainterPath()
            check.moveTo(right - 10, center_y)
            check.lineTo(right - 6, center_y + 4)
            check.lineTo(right, center_y - 5)
            painter.drawPath(check)
        painter.restore()


class PastelComboBox(QComboBox):
    """Combo box whose popup container never inherits a dark Windows surface."""

    def __init__(self, *args, **kwargs) -> None:
        super().__init__(*args, **kwargs)
        self._row_delegate = ComboItemDelegate(self)
        self.setItemDelegate(self._row_delegate)

    def paintEvent(self, event) -> None:
        option = QStyleOptionComboBox()
        self.initStyleOption(option)
        head, tail = ComboItemDelegate.split_text(option.currentText)

        style_painter = QStylePainter(self)
        option.currentText = ""  # the frame only; the label is drawn below
        style_painter.drawComplexControl(QStyle.ComplexControl.CC_ComboBox, option)
        field = self.style().subControlRect(
            QStyle.ComplexControl.CC_ComboBox,
            option,
            QStyle.SubControl.SC_ComboBoxEditField,
            self,
        )
        field = field.adjusted(2, 0, -6, 0)
        enabled = self.isEnabled()

        head_font = QFont(self.font())
        head_font.setBold(True)
        style_painter.setFont(head_font)
        style_painter.setPen(QColor("#22314a" if enabled else "#a2acba"))
        head_width = QFontMetrics(head_font).horizontalAdvance(head)
        style_painter.drawText(
            field, Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter, head
        )
        if tail:
            tail_font = QFont(self.font())
            tail_font.setPointSizeF(max(self.font().pointSizeF() - 0.5, 7.5))
            style_painter.setFont(tail_font)
            style_painter.setPen(QColor("#6a7b8f" if enabled else "#b6bfca"))
            tail_area = field.adjusted(head_width + 10, 0, 0, 0)
            style_painter.drawText(
                tail_area,
                Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter,
                QFontMetrics(tail_font).elidedText(
                    tail, Qt.TextElideMode.ElideRight, tail_area.width()
                ),
            )
        style_painter.end()

        # The native arrow is hidden in the stylesheet; draw a soft chevron chip
        # so the control matches the rest of the app.
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        chip = QRectF(self.width() - 40, self.height() / 2 - 13, 26, 26)
        painter.setPen(Qt.PenStyle.NoPen)
        painter.setBrush(QColor("#e2f4ef" if self.isEnabled() else "#eef1f5"))
        painter.drawRoundedRect(chip, 9, 9)

        pen = QPen(QColor("#1b9c85" if self.isEnabled() else "#a9b3c0"), 2.0)
        pen.setCapStyle(Qt.PenCapStyle.RoundCap)
        pen.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
        painter.setPen(pen)
        painter.setBrush(Qt.BrushStyle.NoBrush)
        center = chip.center()
        chevron = QPainterPath()
        chevron.moveTo(center.x() - 4.5, center.y() - 2.0)
        chevron.lineTo(center.x(), center.y() + 2.8)
        chevron.lineTo(center.x() + 4.5, center.y() - 2.0)
        painter.drawPath(chevron)
        painter.end()

    def showPopup(self) -> None:
        # Qt reinstalls its own delegate whenever the style changes, so claim
        # the rows back right before the list appears.
        if self.itemDelegate() is not self._row_delegate:
            self.setItemDelegate(self._row_delegate)
        self.view().setMouseTracking(True)
        popup = self.view().window()
        popup.setAttribute(Qt.WidgetAttribute.WA_StyledBackground, True)
        popup.setAutoFillBackground(True)
        popup.setContentsMargins(0, 0, 0, 0)
        popup.setStyleSheet(
            "background: #ffffff; border: 1px solid #dbe4ec; "
            "border-radius: 10px; padding: 0;"
        )
        popup_palette = popup.palette()
        for color_group in (
            QPalette.ColorGroup.Active,
            QPalette.ColorGroup.Inactive,
        ):
            popup_palette.setColor(
                color_group, QPalette.ColorRole.Window, QColor("#ffffff")
            )
            popup_palette.setColor(
                color_group, QPalette.ColorRole.Base, QColor("#ffffff")
            )
        popup.setPalette(popup_palette)
        super().showPopup()


class PastelSpinBox(QSpinBox):
    """Spin box with hand-drawn chevrons; Qt stylesheets cannot rotate arrows."""

    def paintEvent(self, event) -> None:
        super().paintEvent(event)
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        pen = QPen(QColor("#1b9c85" if self.isEnabled() else "#a9b3c0"), 1.8)
        pen.setCapStyle(Qt.PenCapStyle.RoundCap)
        pen.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
        painter.setPen(pen)
        painter.setBrush(Qt.BrushStyle.NoBrush)

        option = QStyleOptionSpinBox()
        self.initStyleOption(option)
        for sub_control, points_up in (
            (QStyle.SubControl.SC_SpinBoxUp, True),
            (QStyle.SubControl.SC_SpinBoxDown, False),
        ):
            rect = self.style().subControlRect(
                QStyle.ComplexControl.CC_SpinBox, option, sub_control, self
            )
            center = QRectF(rect).center()
            tip = center.y() - 1.8 if points_up else center.y() + 1.8
            base = center.y() + 1.8 if points_up else center.y() - 1.8
            chevron = QPainterPath()
            chevron.moveTo(center.x() - 3.6, base)
            chevron.lineTo(center.x(), tip)
            chevron.lineTo(center.x() + 3.6, base)
            painter.drawPath(chevron)
        painter.end()


class PastelTableWidget(QTableWidget):
    """Table whose clicks never enter the native Windows selection path."""

    def __init__(self, *args, **kwargs) -> None:
        super().__init__(*args, **kwargs)
        self.hover_row = -1
        self.setMouseTracking(True)
        self.viewport().setMouseTracking(True)

    def _set_hover_row(self, row: int) -> None:
        if row != self.hover_row:
            self.hover_row = row
            self.viewport().update()

    def viewportEvent(self, event) -> bool:
        """Track the hovered row so the whole row can highlight together."""
        event_type = event.type()
        if event_type in (QEvent.Type.MouseMove, QEvent.Type.HoverMove):
            self._set_hover_row(self.indexAt(event.position().toPoint()).row())
        elif event_type in (QEvent.Type.Leave, QEvent.Type.HoverLeave):
            self._set_hover_row(-1)
        return super().viewportEvent(event)

    def mousePressEvent(self, event) -> None:
        index = self.indexAt(event.position().toPoint())
        if index.isValid() and event.button() == Qt.MouseButton.LeftButton:
            self.cellClicked.emit(index.row(), index.column())
        event.accept()

    def mouseReleaseEvent(self, event) -> None:
        event.accept()

    def mouseDoubleClickEvent(self, event) -> None:
        index = self.indexAt(event.position().toPoint())
        if index.isValid() and event.button() == Qt.MouseButton.LeftButton:
            self.cellDoubleClicked.emit(index.row(), index.column())
        event.accept()

    def paintEvent(self, event) -> None:
        super().paintEvent(event)
        selection_model = self.selectionModel()
        if selection_model is None:
            return
        selected_rows = {index.row() for index in selection_model.selectedRows()}
        if not selected_rows:
            return

        painter = QPainter(self.viewport())
        painter.setFont(self.font())
        for row in selected_rows:
            for column in range(self.columnCount()):
                item = self.item(row, column)
                if item is None:
                    continue
                rect = self.visualItemRect(item)
                if not rect.isValid() or not self.viewport().rect().intersects(rect):
                    continue
                painter.fillRect(rect, QColor(SELECTED_BG))
                painter.setPen(QColor(SELECTED_FG))
                painter.drawText(
                    rect.adjusted(10, 0, -8, 0),
                    Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter,
                    item.text(),
                )
        painter.end()


