    def _auto_groups(self) -> list[tuple[str, tuple[str, ...]]]:
        """May raise ValueError when the selection cannot be cut into blocks."""
        columns = self.selected_columns()
        if not columns:
            return []
        axis = self._auto_axis()
        if axis == CHUNK_AXIS:
            return group_columns_by_size(columns, self.chunk_size_spin.value())
        if axis == MARKER_AXIS:
            return group_columns_by_marker(columns)
        return group_columns_by_prefix(columns)

    def _update_auto_preview(self) -> None:
        """Say what the button will build before it is pressed."""
        if not hasattr(self, "auto_preview"):
            return
        try:
            groups = self._auto_groups()
        except ValueError as exc:
            self.auto_preview.setText(str(exc))
            return
        if not groups:
            self.auto_preview.setText(
                "ย้ายตัวแปรมาที่ “ลำดับการต่อ Data” แล้วปุ่มนี้จะแยกให้เป็นหลายรายการในครั้งเดียว"
            )
            return
        sizes = {len(members) for _, members in groups}
        names = [suggest_stacked_name(prefix) for prefix, _ in groups]
        preview = ", ".join(names[:4]) + (" …" if len(names) > 4 else "")
        source_cases = len(self.dataframe) if self.dataframe is not None else 0
        if self._is_stacking() and len(sizes) == 1:
            blocks = sizes.pop()
            self.auto_preview.setText(
                f"จะได้ {len(groups)} ตัวแปร  •  {source_cases:,} เคส × {blocks} ก้อน = "
                f"{source_cases * blocks:,} เคส  ({preview})"
            )
            return
        if self._is_stacking():
            widest = max(sizes)
            spread = ", ".join(f"{blocks} ก้อน" for blocks in sorted(sizes, reverse=True))
            self.auto_preview.setText(
                f"จะได้ {len(groups)} ตัวแปร • จำนวนก้อนไม่เท่ากัน ({spread}) "
                f"จะต่อที่ {widest} ก้อน = {source_cases * widest:,} เคส "
                f"ชุดที่สั้นกว่าเว้นว่างก้อนที่เหลือ  ({preview})"
            )
            return
        self.auto_preview.setText(f"จะได้ {len(groups)} รายการ ({preview})")

