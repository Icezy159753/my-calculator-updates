NAME_TOKEN_RE = re.compile(r"\d+|\D+")
SEPARATORS = "_.-#"
ASCII_LETTERS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"


def _tokens(name: str) -> list[str]:
    """Split a name into runs of digits and non-digits: I_1_a3 -> I_ 1 _a 3."""
    return NAME_TOKEN_RE.findall(name)


def _shape(tokens: Sequence[str]) -> tuple:
    """Names that differ only in their numbers share a shape."""
    return tuple(None if token.isdigit() else token for token in tokens)


def _group_key(tokens: Sequence[str], block: int, block_is_labelled_set: bool = False) -> str:
    """Name of the group a column belongs to once its block number is removed.

    A6_1#1 (block=the '1' after A6_) -> 'A6_1' — the question keeps its family
    name and its item number, because what is left after the block is only a
    number. I_1_a3_1 -> 'a3_1' — here the text after the block already names
    the question, so the constant lead-in is dropped.

    `block_is_labelled_set` marks the one case where letters also have to go:
    an array name whose set number is introduced by a label, A5_1_G1#1. There
    the 'G' belongs to the block, so dropping it leaves 'A5_1_1'. Everywhere
    else the letters name the question ('a' in I_1_a3) and must stay, or two
    different questions would collapse into the same group.
    """
    head = list(tokens[:block])
    if block_is_labelled_set and block >= 1 and head:
        head[block - 1] = head[block - 1].rstrip(ASCII_LETTERS)
    before = "".join(head).rstrip(SEPARATORS)
    after = "".join(tokens[block + 1 :]).lstrip(SEPARATORS)
    if any(character.isalpha() for character in after):
        return after
    if after:
        return f"{before}_{after}" if before else after
    return before


def _array_positions(shape: Sequence) -> tuple[int | None, int | None]:
    """For SPSS array names, where the set number and the item number sit.

    A6_1#1   -> set '1' (attached with '_'), item '1' (after '#').
    A5_1_G1#1-> set '1' (attached with '_G'), item '1' (after '#'). The block
                may be introduced by a labelled separator, not a bare one.
    B2#1     -> no set number: the '2' belongs to the question name, so only the
                item position is returned, which keeps B2 and B3 apart.
    """
    markers = [
        position
        for position, token in enumerate(shape)
        if token is not None and "#" in token
    ]
    if not markers:
        return None, None
    marker = markers[0]
    item = marker + 1 if marker + 1 < len(shape) and shape[marker + 1] is None else None
    set_position = None
    if marker >= 1 and shape[marker - 1] is None:
        lead = shape[marker - 2] if marker >= 2 else ""
        # A separator anywhere in the lead-in means the number that follows is a
        # block, not part of the question name: '_' in A6_1#1, '_G' in A5_1_G1#1.
        # A bare 'B' (B2#1) has none, so that '2' stays with the question.
        if lead and any(character in SEPARATORS for character in lead):
            set_position = marker - 1
    return set_position, item


def _pick_block(candidates: Sequence[int | None], varying: Sequence[int]) -> int | None:
    """Prefer a number that actually changes; fall back to the convention."""
    for position in candidates:
        if position is not None and position in varying:
            return position
    for position in candidates:
        if position is not None:
            return position
    return None


def _group_columns(
    columns: Sequence[str], use_first_varying: bool
) -> list[tuple[str, tuple[str, ...]]]:
    """Group columns by everything except the number that marks the block.

    Which number that is cannot be read off a single name — A6_1#1 carries the
    block before the '#', B2#1 after it, and I_1_a1 in the middle. So the
    numbers that actually change across the selection are found first, then one
    of them is taken as the block: the first varying number stacks the sets
    (A6_1#1 + A6_2#1 + …), the last one stacks each set's own items
    (A6_1#1 + A6_1#2 + …).
    """
    names = [str(column) for column in columns]
    tokens_by_name = {name: _tokens(name) for name in names}

    shapes: dict[tuple, list[str]] = {}
    for name in names:
        shapes.setdefault(_shape(tokens_by_name[name]), []).append(name)

    block_by_shape: dict[tuple, int | None] = {}
    set_by_shape: dict[tuple, int | None] = {}
    for shape, members in shapes.items():
        varying = [
            position
            for position, token in enumerate(shape)
            if token is None
            and len({tokens_by_name[member][position] for member in members}) > 1
        ]
        set_position, item_position = _array_positions(shape)
        set_by_shape[shape] = set_position
        if set_position is not None or item_position is not None:
            # SPSS array name: '#' says which number is the item.
            candidates = (
                (set_position, item_position)
                if use_first_varying
                else (item_position, set_position)
            )
            block_by_shape[shape] = _pick_block(candidates, varying)
        elif varying:
            block_by_shape[shape] = varying[0] if use_first_varying else varying[-1]
        else:
            block_by_shape[shape] = None

    grouped: dict[str, list[str]] = {}
    order: list[str] = []
    for name in names:
        tokens = tokens_by_name[name]
        shape = _shape(tokens)
        block = block_by_shape[shape]
        # Only an array set number may carry a label ('_G' in A5_1_G1#1).
        labelled_set = (
            block is not None
            and block == set_by_shape[shape]
            and block >= 1
            and tokens[block - 1][-1:].isalpha()
        )
        key = name if block is None else _group_key(tokens, block, labelled_set)
        if key not in grouped:
            grouped[key] = []
            order.append(key)
        grouped[key].append(name)
    return [(key, tuple(grouped[key])) for key in order]


def group_columns_by_prefix(
    columns: Sequence[str],
) -> list[tuple[str, tuple[str, ...]]]:
    """One group per set: A5_1#1 … A5_1#8 stack together."""
    return _group_columns(columns, use_first_varying=False)


def _common_prefix(values: Sequence[str]) -> str:
    if not values:
        return ""
    first, last = min(values), max(values)
    length = 0
    while length < len(first) and length < len(last) and first[length] == last[length]:
        length += 1
    return first[:length]


def group_columns_by_marker(
    columns: Sequence[str],
) -> list[tuple[str, tuple[str, ...]]]:
    """One group per question: A6_1#1 + A6_2#1 + … + A6_5#1 stack together.

    This is the axis that stacks the blocks (products) and keeps one new
    variable per question, which is what penalty/correlation setups need. A
    question asked once per block (B2#1 … B2#5) forms a single group instead of
    being split apart and mixed into another question's groups.
    """
    return _group_columns(columns, use_first_varying=True)


def group_columns_by_size(
    columns: Sequence[str], size: int
) -> list[tuple[str, tuple[str, ...]]]:
    """Cut the ordered selection into consecutive blocks of `size` columns.

    The escape hatch for names no rule can read: 15 columns with size 5 become
    three new variables from columns 1–5, 6–10 and 11–15, in the order the user
    arranged them. Each block still gets a name from its own contents when the
    columns inside it do follow a pattern.
    """
    if size < 1:
        raise ValueError("จำนวนตัวแปรต่อก้อนต้องมากกว่า 0")
    names = [str(column) for column in columns]
    if len(names) % size:
        raise ValueError(
            f"เลือกมา {len(names)} ตัวแปร แบ่งก้อนละ {size} ไม่ลงตัว "
            f"(เหลือเศษ {len(names) % size} ตัว) — เพิ่มหรือเอาตัวแปรออกให้ลงตัวก่อน"
        )

    groups: list[tuple[str, tuple[str, ...]]] = []
    for start in range(0, len(names), size):
        chunk = tuple(names[start : start + size])
        inner = _group_columns(chunk, use_first_varying=True)
        key = inner[0][0] if len(inner) == 1 else chunk[0]
        groups.append((key, chunk))
    return groups


JOB_SHEET = "jobs"
SOURCE_NAME_COLUMN = "ไฟล์ต้นทาง"
SOURCE_PATH_COLUMN = "ที่อยู่ไฟล์ต้นทาง"


def block_count(jobs: Sequence[TransformJob]) -> int:
    """Blocks the output will have: the widest job decides."""
    return max((len(job.source_columns) for job in jobs), default=0)


def split_jobs_by_block(
    jobs: Sequence[TransformJob],
) -> list[tuple[int, list[TransformJob]]]:
    """Group jobs by how many blocks they carry, in first-seen order.

    Everything lands in one output; this only reports the mix, so the app can
    say which jobs are padded with empty blocks.
    """
    parts: dict[int, list[TransformJob]] = {}
    for job in jobs:
        parts.setdefault(len(job.source_columns), []).append(job)
    return list(parts.items())


@dataclass(frozen=True, slots=True)
class SavedSetting:
    """A setup read back from Excel, plus the file it was built from."""

    jobs: list[TransformJob]
    source_name: str = ""
    source_path: str = ""


def save_jobs_to_excel(
    path: Path | str,
    jobs: Sequence[TransformJob],
    source_path: Path | str = "",
) -> None:
    """Write the queued jobs to a one-sheet workbook so the setup can be reused."""
    if not jobs:
        raise ValueError("ยังไม่มีรายการให้บันทึก")
    source = Path(source_path) if source_path else None
    rows = [
        {
            "ลำดับ": position,
            "ตัวแปรใหม่": job.new_name,
            "Variable Label": job.variable_label,
            "จำนวนตัวแปรต้นทาง": len(job.source_columns),
            "ตัวแปรต้นทางตามลำดับ": " ".join(job.source_columns),
            SOURCE_NAME_COLUMN: source.name if source else "",
            SOURCE_PATH_COLUMN: str(source) if source else "",
        }
        for position, job in enumerate(jobs, start=1)
    ]
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        pd.DataFrame(rows).to_excel(writer, sheet_name=JOB_SHEET, index=False)


def _first_text(frame: pd.DataFrame, column: str) -> str:
    if column not in frame.columns:
        return ""
    for value in frame[column]:
        text = "" if pd.isna(value) else str(value).strip()
        if text:
            return text
    return ""


def load_jobs_from_excel(path: Path | str) -> SavedSetting:
    """Read a saved setup back. The first sheet is used whatever it is named."""
    # keep_default_na: a variable really named NA, NULL or None must survive the
    # trip instead of being read back as a missing value.
    sheets = pd.read_excel(
        path, sheet_name=None, engine="openpyxl", keep_default_na=False
    )
    if not sheets:
        raise ValueError("ไฟล์นี้ไม่มีชีตข้อมูล")
    frame = sheets.get(JOB_SHEET, next(iter(sheets.values())))
    for column in ("ตัวแปรใหม่", "ตัวแปรต้นทางตามลำดับ"):
        if column not in frame.columns:
            raise ValueError(f"ไฟล์นี้ไม่มีคอลัมน์ '{column}'")

    jobs: list[TransformJob] = []
    # records, not itertuples: column names with spaces get renamed by itertuples
    for position, values in enumerate(frame.to_dict(orient="records"), start=1):
        new_name = str(values["ตัวแปรใหม่"] or "").strip()
        sources = str(values["ตัวแปรต้นทางตามลำดับ"] or "").replace(",", " ").split()
        if not new_name or not sources:
            raise ValueError(f"แถวที่ {position} ไม่มีชื่อตัวแปรใหม่หรือตัวแปรต้นทาง")
        label = values.get("Variable Label", "")
        label = "" if pd.isna(label) else str(label).strip()
        jobs.append(TransformJob(tuple(sources), new_name, label))
    return SavedSetting(
        jobs,
        _first_text(frame, SOURCE_NAME_COLUMN),
        _first_text(frame, SOURCE_PATH_COLUMN),
    )


def shared_variable_label(labels: Sequence[str]) -> str:
    """Keep only the part every source label shares.

    Stacking C1-Overall aroma … C5-Overall aroma must not keep the C1 marker,
    so the common tail 'Overall aroma' becomes the label of the new variable.
    """
    cleaned = [str(label).strip() for label in labels if str(label).strip()]
    if not cleaned:
        return ""
    if len(set(cleaned)) == 1:
        return cleaned[0]
    reversed_common = _common_prefix([label[::-1] for label in cleaned])
    # The shared tail of 'A5_1) กลิ่นโดยรวม' … 'A5_5) กลิ่นโดยรวม' starts with the
    # bracket left behind by the varying code, so strip that punctuation too.
    tail = reversed_common[::-1].lstrip(" -–—_.,:;#/|)]}>")
    return tail if len(tail) >= 3 else cleaned[0]


def suggest_stacked_name(prefix: str, existing_names: Iterable[str] = ()) -> str:
    """Propose a valid, unused SPSS name for a grouped prefix (A5_1 -> NA5_1)."""
    cleaned = re.sub(r"[^A-Za-z0-9_@$]", "_", prefix.strip()) or "VAR"
    cleaned = cleaned[:1].upper() + cleaned[1:]  # a3_1 -> A3_1, so NA3_1
    candidate = f"N{cleaned}"[:64]
    taken = {str(name).casefold() for name in existing_names}
    if candidate.casefold() not in taken:
        return candidate
    for serial in range(2, 1000):
        suffix = f"_{serial}"
        alternative = f"{candidate[: 64 - len(suffix)]}{suffix}"
        if alternative.casefold() not in taken:
            return alternative
    raise ValueError(f"ตั้งชื่อตัวแปรใหม่จาก {prefix} ไม่ได้ เพราะชื่อซ้ำทั้งหมด")


def validate_new_variable_name(name: str, existing_names: Iterable[str] = ()) -> str:
    """Validate and return a normalized SPSS variable name."""
    normalized = name.strip()
    if not normalized:
        raise ValueError("กรุณาระบุชื่อตัวแปรใหม่")
    if not SPSS_NAME_RE.fullmatch(normalized):
        raise ValueError(
            "ชื่อตัวแปรต้องขึ้นต้นด้วย A-Z, a-z หรือ @ และใช้ได้เฉพาะ "
            "ตัวอักษร ตัวเลข _ @ # $ (ไม่เกิน 64 ตัวอักษร)"
        )
    if normalized.casefold() in {str(item).casefold() for item in existing_names}:
        raise ValueError(f"มีตัวแปรชื่อ {normalized} อยู่ในไฟล์แล้ว")
    return normalized


def _is_string_series(series: pd.Series) -> bool:
    return bool(
        pd.api.types.is_object_dtype(series.dtype)
        or pd.api.types.is_string_dtype(series.dtype)
        or isinstance(series.dtype, pd.CategoricalDtype)
    )


def _user_missing_mask(
    series: pd.Series, rules: Sequence[Any] | None
) -> pd.Series:
    mask = series.isna()
    if _is_string_series(series):
        mask |= series.astype("string").str.strip().eq("").fillna(True)

    for rule in rules or ():
        if isinstance(rule, Mapping) and "lo" in rule and "hi" in rule:
            try:
                mask |= series.between(rule["lo"], rule["hi"], inclusive="both")
            except TypeError:
                continue
        else:
            try:
                mask |= series.eq(rule)
            except (TypeError, ValueError):
                continue
    return mask.fillna(True)


def combine_first_non_missing(
    dataframe: pd.DataFrame,
    source_columns: Sequence[str],
    new_name: str,
    missing_ranges: Mapping[str, Sequence[Any]] | None = None,
) -> CombineResult:
    """Append a variable using the first non-missing source value per row."""
    if not source_columns:
        raise ValueError("กรุณาเลือกอย่างน้อย 1 ตัวแปร")
    missing_columns = [name for name in source_columns if name not in dataframe.columns]
    if missing_columns:
        raise ValueError(f"ไม่พบตัวแปร: {', '.join(missing_columns)}")
    validate_new_variable_name(new_name, dataframe.columns)

    string_flags = [_is_string_series(dataframe[name]) for name in source_columns]
    if len(set(string_flags)) > 1:
        raise ValueError("ไม่สามารถรวมตัวแปรชนิดข้อความและตัวเลขไว้ด้วยกันได้")

    output = dataframe.copy()
    if string_flags[0]:
        combined = pd.Series(pd.NA, index=output.index, dtype="string")
    else:
        combined = pd.Series(float("nan"), index=output.index, dtype="float64")

    filled_counts: dict[str, int] = {}
    rules_by_name = missing_ranges or {}
    for column in source_columns:
        source = output[column]
        source_missing = _user_missing_mask(source, rules_by_name.get(column))
        available = combined.isna() & ~source_missing
        if string_flags[0]:
            combined.loc[available] = source.loc[available].astype("string")
        else:
            combined.loc[available] = pd.to_numeric(source.loc[available], errors="coerce")
        filled_counts[column] = int(available.sum())

    output[new_name] = combined
    warnings: list[str] = []
    unused = [name for name, count in filled_counts.items() if count == 0]
    if unused:
        warnings.append(f"ไม่มีค่าถูกนำมาจาก: {', '.join(unused)}")
    return CombineResult(
        dataframe=output,
        filled_counts=filled_counts,
        missing_count=int(combined.isna().sum()),
        warnings=warnings,
    )


def stack_columns(
    dataframe: pd.DataFrame,
    source_columns: Sequence[str],
    new_name: str,
    missing_ranges: Mapping[str, Sequence[Any]] | None = None,
    drop_missing: bool = False,
) -> CombineResult:
    """Restructure selected columns into one new variable, case by case.

    This mirrors SPSS VARSTOCASES: non-selected columns are repeated for each
    selected source variable and the selected source columns are replaced by
    the new long-form variable.
    """
    if not source_columns:
        raise ValueError("กรุณาเลือกอย่างน้อย 1 ตัวแปร")
    missing_columns = [name for name in source_columns if name not in dataframe.columns]
    if missing_columns:
        raise ValueError(f"ไม่พบตัวแปร: {', '.join(missing_columns)}")
    validate_new_variable_name(new_name, dataframe.columns)

    string_flags = [_is_string_series(dataframe[name]) for name in source_columns]
    if len(set(string_flags)) > 1:
        raise ValueError("ไม่สามารถต่อแนวตั้งระหว่างตัวแปรชนิดข้อความและตัวเลขได้")

    source_frame = dataframe.loc[:, source_columns]
    rules_by_name = missing_ranges or {}
    missing_frame = pd.DataFrame(
        {
            name: _user_missing_mask(source_frame[name], rules_by_name.get(name))
            for name in source_columns
        },
        index=dataframe.index,
    )
    keep_columns = [name for name in dataframe.columns if name not in source_columns]
    repeats = len(source_columns)
    # Block by block: every case for block 1, then every case for block 2.
    result = pd.concat(
        [dataframe.loc[:, keep_columns]] * repeats, ignore_index=True
    )
    result[new_name] = source_frame.to_numpy().reshape(-1, order="F")
    missing_values = missing_frame.to_numpy(dtype=bool).reshape(-1, order="F")

    filled_counts = {
        name: int((~missing_frame[name]).sum()) for name in source_columns
    }
    if drop_missing:
        result = result.loc[~missing_values].reset_index(drop=True)
        missing_count = 0
    else:
        missing_count = int(missing_values.sum())

    warnings: list[str] = []
    unused = [name for name, count in filled_counts.items() if count == 0]
    if unused:
        warnings.append(f"ไม่มีค่าถูกนำมาจาก: {', '.join(unused)}")
    return CombineResult(
        dataframe=result,
        filled_counts=filled_counts,
        missing_count=missing_count,
        warnings=warnings,
    )


def _validate_jobs(dataframe: pd.DataFrame, jobs: Sequence[TransformJob]) -> None:
    if not jobs:
        raise ValueError("กรุณาเพิ่มรายการต่อ Data อย่างน้อย 1 รายการ")
    pending_names: list[str] = []
    for job in jobs:
        if not job.source_columns:
            raise ValueError(f"รายการ {job.new_name or '(ไม่มีชื่อ)'} ไม่มีตัวแปรต้นทาง")
        validate_new_variable_name(job.new_name, [*dataframe.columns, *pending_names])
        missing = [name for name in job.source_columns if name not in dataframe.columns]
        if missing:
            raise ValueError(f"ไม่พบตัวแปร: {', '.join(missing)}")
        string_flags = [_is_string_series(dataframe[name]) for name in job.source_columns]
        if len(set(string_flags)) > 1:
            raise ValueError(
                f"รายการ {job.new_name} มีตัวแปรข้อความและตัวเลขปะปนกัน"
            )
        pending_names.append(job.new_name)


def combine_jobs(
    dataframe: pd.DataFrame,
    jobs: Sequence[TransformJob],
    mode: str,
    missing_ranges: Mapping[str, Sequence[Any]] | None = None,
    index_name: str | None = None,
) -> BatchResult:
    """Apply multiple queued transformations and return one output dataset."""
    _validate_jobs(dataframe, jobs)
    rules_by_name = missing_ranges or {}
    warnings: list[str] = []
    filled_counts: dict[str, dict[str, int]] = {}
    missing_counts: dict[str, int] = {}

    if mode in STACKING_MODES:
        if index_name:
            validate_new_variable_name(
                index_name, [*dataframe.columns, *(job.new_name for job in jobs)]
            )
        all_sources = [name for job in jobs for name in job.source_columns]
        duplicates = sorted(
            {name for name in all_sources if all_sources.count(name) > 1}
        )
        if duplicates:
            raise ValueError(
                "ตัวแปรต้นทางถูกใช้ซ้ำมากกว่า 1 รายการ: " + ", ".join(duplicates)
            )

        # One file holds every job, so the block count is the widest job. A job
        # asked over fewer blocks (Part B over 3 of the 5 products) is padded
        # with empty blocks at the end, exactly like SPSS reading a blank
        # variable inside VARSTOCASES.
        repeats = block_count(jobs)
        # APPEND_MODE leaves the chosen variables where they are and only adds
        # the stacked variable at the end; STACK_MODE consumes them.
        keep_columns = [
            name
            for name in dataframe.columns
            if mode == APPEND_MODE or name not in all_sources
        ]
        # Block by block, not case by case: every case for block 1, then every
        # case for block 2, so the file needs no sorting after the restructure.
        output = pd.concat(
            [dataframe.loc[:, keep_columns]] * repeats, ignore_index=True
        )
        for job in jobs:
            source_frame = dataframe.loc[:, job.source_columns]
            missing_frame = pd.DataFrame(
                {
                    name: _user_missing_mask(
                        source_frame[name], rules_by_name.get(name)
                    )
                    for name in job.source_columns
                },
                index=dataframe.index,
            )
            padding = repeats - len(job.source_columns)
            if padding:
                blank = pd.DataFrame(
                    {
                        f"__pad{position}": pd.Series(
                            float("nan"), index=dataframe.index, dtype="float64"
                        )
                        for position in range(padding)
                    },
                    index=dataframe.index,
                )
                source_frame = pd.concat([source_frame, blank], axis=1)
            output[job.new_name] = source_frame.to_numpy().reshape(-1, order="F")
            filled_counts[job.new_name] = {
                name: int((~missing_frame[name]).sum()) for name in job.source_columns
            }
            missing_counts[job.new_name] = int(
                missing_frame.to_numpy(dtype=bool).sum()
            )
        if index_name:
            index_values = [
                block
                for block in range(1, repeats + 1)
                for _ in range(len(dataframe))
            ]
            casefolded_columns = {
                str(column).casefold(): position
                for position, column in enumerate(output.columns)
            }
            insert_at = 0
            for anchor in ("SBJNUM", "KEY"):
                anchor_position = casefolded_columns.get(anchor.casefold())
                if anchor_position is not None:
                    insert_at = anchor_position + 1
                    break
            output.insert(insert_at, index_name, index_values)
    elif mode == COALESCE_MODE:
        output = dataframe.copy()
        for job in jobs:
            result = combine_first_non_missing(
                output,
                job.source_columns,
                job.new_name,
                missing_ranges=rules_by_name,
            )
            output = result.dataframe
            filled_counts[job.new_name] = result.filled_counts
            missing_counts[job.new_name] = result.missing_count
            warnings.extend(result.warnings)
    else:
        raise ValueError(f"โหมดการรวมไม่ถูกต้อง: {mode}")

    return BatchResult(
        dataframe=output,
        filled_counts=filled_counts,
        missing_counts=missing_counts,
        warnings=warnings,
    )


def escape_spss_label(label: str) -> str:
    return label.replace("'", "''").replace("\r", " ").replace("\n", " ")


def generate_spss_syntax(
    source_file: str | Path,
    output_file: str | Path,
    source_columns: Sequence[str],
    new_name: str,
    variable_label: str = "",
    mode: str = STACK_MODE,
    is_string: bool = False,
    string_width: int = 255,
    index_name: str | None = None,
) -> str:
    """Backward-compatible wrapper for a single transformation job."""
    widths = {new_name: string_width} if is_string else {}
    return generate_batch_spss_syntax(
        source_file,
        output_file,
        [TransformJob(tuple(source_columns), new_name, variable_label)],
        mode,
        string_widths=widths,
        index_name=index_name,
    )


def generate_batch_spss_syntax(
    source_file: str | Path,
    output_file: str | Path,
    jobs: Sequence[TransformJob],
    mode: str = STACK_MODE,
    string_widths: Mapping[str, int] | None = None,
    index_name: str | None = None,
    save_keep_prefix: Sequence[str] | None = None,
) -> str:
    """Generate one SPSS syntax file for all queued transformation jobs."""
    if not jobs:
        raise ValueError("กรุณาเพิ่มรายการต่อ Data อย่างน้อย 1 รายการ")
    seen_names: list[str] = []
    for job in jobs:
        validate_new_variable_name(job.new_name, seen_names)
        if not job.source_columns:
            raise ValueError(f"รายการ {job.new_name} ไม่มีตัวแปรต้นทาง")
        seen_names.append(job.new_name)
    source_path = str(Path(source_file).resolve()).replace("'", "''")
    output_path = str(Path(output_file).resolve()).replace("'", "''")
    lines = [
        "* Generated by SPSS Transformation.",
        f"GET FILE='{source_path}'.",
        "",
    ]
    if mode in STACKING_MODES:
        if index_name:
            validate_new_variable_name(index_name, seen_names)
        blocks = block_count(jobs)
        width_by_name = string_widths or {}
        # VARSTOCASES always eats the variables it reads. To keep them, it is
        # fed throw-away copies instead and the originals ride along untouched.
        copies: dict[str, str] = {}
        if mode == APPEND_MODE:
            for job in jobs:
                for column in job.source_columns:
                    if column in copies:
                        continue
                    copy_name = f"SPSSTCOPY{len(copies) + 1}"
                    copies[column] = copy_name
                    if job.new_name in width_by_name:
                        width = max(1, min(int(width_by_name[job.new_name]), 32767))
                        lines.append(f"STRING {copy_name} (A{width}).")
                    lines.append(f"COMPUTE {copy_name} = {column}.")
        # VARSTOCASES insists every /MAKE holds the same number of variables, so
        # a job with fewer blocks borrows empty helper variables to fill up. They
        # are dropped again right after the restructure.
        pad_needed = max((blocks - len(job.source_columns) for job in jobs), default=0)
        pad_names = [f"SPSSTBLANK{position + 1}" for position in range(pad_needed)]
        # VARSTOCASES writes case by case; this keeps the original case order so
        # the file can be sorted into block-by-block order afterwards.
        order_name = "SPSSTORDER" if index_name else ""
        if order_name:
            lines.append(f"COMPUTE {order_name} = $CASENUM.")
        if pad_names:
            lines.extend(f"COMPUTE {name} = $SYSMIS." for name in pad_names)
        if order_name or pad_names or copies:
            lines.extend(["EXECUTE.", ""])
        lines.append("VARSTOCASES")
        for job in jobs:
            padding = blocks - len(job.source_columns)
            sources = [copies.get(name, name) for name in job.source_columns]
            columns = [*sources, *pad_names[:padding]]
            lines.append(f" /MAKE {job.new_name} FROM {' '.join(columns)}")
        if index_name:
            lines.append(f" /INDEX={index_name}")
        lines.append(" /NULL=KEEP.")
        if order_name:
            lines.append(f"SORT CASES BY {index_name} {order_name}.")
        dropped = [*pad_names, *([order_name] if order_name else [])]
        if dropped:
            lines.append(f"DELETE VARIABLES {' '.join(dropped)}.")
    elif mode == COALESCE_MODE:
        width_by_name = string_widths or {}
        for job in jobs:
            is_string_job = job.new_name in width_by_name
            if is_string_job:
                width = max(1, min(int(width_by_name[job.new_name]), 32767))
                lines.extend(
                    [f"STRING {job.new_name} (A{width}).", f"COMPUTE {job.new_name} = ''."]
                )
            else:
                lines.append(f"COMPUTE {job.new_name} = $SYSMIS.")
            for index, column in enumerate(job.source_columns):
                keyword = "DO IF" if index == 0 else "ELSE IF"
                condition = f"NOT MISSING({column})"
                if is_string_job:
                    condition += f" AND RTRIM({column}) <> ''"
                lines.extend(
                    [
                        f"{keyword} {condition}.",
                        f"    COMPUTE {job.new_name} = {column}.",
                    ]
                )
            lines.extend(["END IF.", ""])
    else:
        raise ValueError(f"โหมดการรวมไม่ถูกต้อง: {mode}")

    for job in jobs:
        label = job.variable_label.strip() or (
            f"{'Stacked' if mode in STACKING_MODES else 'Combined'} from "
            f"{', '.join(job.source_columns)}"
        )
        lines.append(
            f"VARIABLE LABELS {job.new_name} '{escape_spss_label(label)}'."
        )
    if mode in STACKING_MODES and index_name:
        group_count = block_count(jobs)
        lines.extend(
            [
                f"VARIABLE LABELS {index_name} 'Source data block index'.",
                f"VALUE LABELS {index_name}",
                *(f" {value} 'Data block {value}'" for value in range(1, group_count + 1)),
                ".",
            ]
        )
    lines.extend(["EXECUTE.", "", f"SAVE OUTFILE='{output_path}'"])
    if mode in STACKING_MODES and index_name:
        ordered_prefix = [*(save_keep_prefix or ()), index_name, "ALL"]
        lines.append(f" /KEEP={' '.join(ordered_prefix)}")
    lines.extend([" /COMPRESSED.", "EXECUTE.", ""])
    return "\n".join(lines)


def merged_value_labels(
    source_columns: Sequence[str],
    labels_by_variable: Mapping[str, Mapping[Any, str]],
) -> tuple[dict[Any, str], list[str]]:
    """Merge compatible value labels and report label conflicts."""
    merged: dict[Any, str] = {}
    conflicts: list[str] = []
    for column in source_columns:
        for value, label in labels_by_variable.get(column, {}).items():
            if value in merged and merged[value] != label:
                conflicts.append(f"ค่า {value}: '{merged[value]}' / '{label}'")
                continue
            merged[value] = label
    return merged, conflicts


