def build_app_icon() -> QIcon:
    """Draw the app icon in code, so the program stays a single file.

    The mark shows what the program does: several source columns collapsing
    into one stacked variable.
    """
    icon = QIcon()
    for size in (16, 24, 32, 48, 64, 128, 256):
        pixmap = QPixmap(size, size)
        pixmap.fill(QColor(0, 0, 0, 0))
        painter = QPainter(pixmap)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)

        gradient = QLinearGradient(0, 0, 0, size)
        gradient.setColorAt(0.0, QColor("#25b096"))
        gradient.setColorAt(1.0, QColor("#137a67"))
        plate = QPainterPath()
        plate.addRoundedRect(0.0, 0.0, float(size), float(size), size * 0.22, size * 0.22)
        painter.fillPath(plate, QBrush(gradient))

        painter.setPen(Qt.PenStyle.NoPen)
        painter.setBrush(QColor("#ffffff"))
        # the source columns — fewer, fatter bars when the icon is tiny, or
        # the gaps between them close up and the mark turns into a smudge
        bar_height = size * 0.12 if size <= 32 else size * 0.11
        if size <= 32:
            columns = ((0.20, 0.60),)  # one bar reads cleanly; three would blur
        else:
            columns = ((0.20, 0.16), (0.42, 0.16), (0.64, 0.16))
        for left, bar_width in columns:
            painter.drawRoundedRect(
                QRectF(size * left, size * 0.22, size * bar_width, bar_height),
                bar_height * 0.45,
                bar_height * 0.45,
            )
        # arrow: they become one
        arrow = QPainterPath()
        arrow.moveTo(size * 0.36, size * 0.44)
        arrow.lineTo(size * 0.64, size * 0.44)
        arrow.lineTo(size * 0.50, size * 0.63)
        arrow.closeSubpath()
        painter.fillPath(arrow, QColor("#ffffff"))
        # the stacked result
        painter.drawRoundedRect(
            QRectF(size * 0.20, size * 0.70, size * 0.60, bar_height),
            bar_height * 0.45,
            bar_height * 0.45,
        )
        painter.end()
        icon.addPixmap(pixmap)
    return icon


