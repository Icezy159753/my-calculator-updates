    def open_file(self) -> None:
        filename, _ = QFileDialog.getOpenFileName(
            self, "เลือกไฟล์ SPSS", "", "SPSS Data Files (*.sav *.zsav)"
        )
        if not filename:
            return
        self._busy("กำลังโหลดไฟล์ SPSS...")
        self._set_ready(False)
        try:
            dataframe, metadata = pyreadstat.read_sav(
                filename, apply_value_formats=False, user_missing=True
            )
        except Exception as exc:
            self._busy("โหลดไฟล์ไม่สำเร็จ", False)
            self._message("error", "เปิดไฟล์ไม่ได้", str(exc))
            return

        self.source_path = Path(filename)
        self.dataframe = dataframe
        self.metadata = metadata
        self.current_result = None
        self.jobs.clear()
        self.jobs_table.setRowCount(0)
        self.file_label.setText(self.source_path.name)
        self.file_label.setToolTip(str(self.source_path))
        self.summary_label.setText(
            f"{len(dataframe):,} เคส  •  {len(dataframe.columns):,} ตัวแปร"
        )
        self.summary_label.setVisible(True)
        self.available_list.clear()
        self.selected_list.clear()
        labels = getattr(metadata, "column_names_to_labels", {}) or {}
        for name in dataframe.columns:
            label = labels.get(name) or ""
            item = QListWidgetItem(f"{name}  —  {label}" if label else str(name))
            item.setData(Qt.ItemDataRole.UserRole, str(name))
            item.setToolTip(label)
            self.available_list.addItem(item)
        self.stats_label.clear()
        self._set_ready(True)
        self._update_queue_state()
        self._update_auto_preview()
        # A file that already carries an Index has been stacked once already;
        # stacking it again multiplies the cases instead of keeping them.
        already_stacked = [
            str(column)
            for column in dataframe.columns
            if str(column).casefold().startswith("index")
        ]
        if already_stacked:
            self._busy(
                f"โหลดไฟล์เรียบร้อย — ไฟล์นี้มีตัวแปร {already_stacked[0]} อยู่แล้ว "
                "จึงน่าจะเป็นไฟล์ที่ต่อ Data มาแล้ว ถ้าต่อซ้ำจำนวนเคสจะคูณเพิ่มอีก",
                False,
            )
        else:
            self._busy("โหลดไฟล์เรียบร้อย", False)

    def filter_variables(self, text: str) -> None:
        needle = text.strip().casefold()
        for row in range(self.available_list.count()):
            item = self.available_list.item(row)
            item.setHidden(bool(needle and needle not in item.text().casefold()))

    def selected_columns(self) -> list[str]:
        return [
            str(self.selected_list.item(i).data(Qt.ItemDataRole.UserRole))
            for i in range(self.selected_list.count())
        ]

    def add_selected(self) -> None:
        existing = set(self.selected_columns())
        for item in self.available_list.selectedItems():
            name = str(item.data(Qt.ItemDataRole.UserRole))
            if name not in existing:
                clone = QListWidgetItem(item.text())
                clone.setData(Qt.ItemDataRole.UserRole, name)
                clone.setToolTip(item.toolTip())
                self.selected_list.addItem(clone)
                existing.add(name)
        self.invalidate_preview()

    def remove_selected(self) -> None:
        for item in list(self.selected_list.selectedItems()):
            self.selected_list.takeItem(self.selected_list.row(item))
        self.invalidate_preview()

    def move_selected(self, direction: int) -> None:
        row = self.selected_list.currentRow()
        target = row + direction
        if row < 0 or target < 0 or target >= self.selected_list.count():
            return
        item = self.selected_list.takeItem(row)
        self.selected_list.insertItem(target, item)
        self.selected_list.setCurrentRow(target)
        self.invalidate_preview()

    def invalidate_preview(self) -> None:
        self.current_result = None
