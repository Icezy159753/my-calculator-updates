    def read_general_file_content(self, filepath):
        _, extension = os.path.splitext(filepath)
        content = ""
        try:
            if extension == '.docx':
                if not LIBS_INSTALLED:
                    return "[Error: ไม่สามารถอ่าน .docx ได้]"
                doc = docx.Document(filepath)
                full_text = [para.text for para in doc.paragraphs]
                for table in doc.tables:
                    for row in table.rows:
                        for cell in row.cells:
                            full_text.append(cell.text)
                content = '\n'.join(full_text)
            elif extension in ['.xlsx', '.xls']:
                if not LIBS_INSTALLED:
                    return "[Error: ไม่สามารถอ่าน Excel ได้]"
                workbook = openpyxl.load_workbook(filepath, data_only=True)
                full_text = []
                for sheet_name in workbook.sheetnames:
                    sheet = workbook[sheet_name]
                    sheet_text = []
                    for row in sheet.iter_rows():
                        row_text = [str(cell.value) if cell.value is not None else "" for cell in row]
                        line = "\t".join(row_text).rstrip("\t")
                        if line.strip():
                            sheet_text.append(line)
                    full_text.append(f"=== Sheet: {sheet_name} ===\n" + '\n'.join(sheet_text))
                content = '\n\n'.join(full_text)
            else:
                with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
                    content = f.read()
        except Exception as e:
            content = f"[เกิดข้อผิดพลาดในการอ่านไฟล์ {os.path.basename(filepath)}: {e}]"
        # ลดบรรทัดว่างซ้ำ ๆ (Word มักมีบรรทัดว่างจำนวนมาก) เพื่อลดขนาด Prompt
        content = re.sub(r'[ \t]+\n', '\n', content)
        content = re.sub(r'\n{3,}', '\n\n', content)
        return content

