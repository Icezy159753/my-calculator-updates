    def _autosize_table_columns(self, kind=None, event=None):
        """แบ่งความกว้างคอลัมน์ให้พอดีกับความกว้างของตาราง"""
        if kind is None:
            kind = self._current_kind()
        tree = self.trees.get(kind)
        if tree is None:
            return
        avail = tree.winfo_width()
        if avail < 80 or abs(avail - self._last_tree_w.get(kind, 0)) < 5:
            return
        self._last_tree_w[kind] = avail
        fixed = {"Name": 115, "Variable": 100, "Value": 55}
        specs = self.TABLE_SPECS[kind]
        flex = [c for c, _, _ in specs if c not in fixed]
        fixed_total = sum(fixed.get(c, 0) for c, _, _ in specs)
        remain = max(200 * len(flex), avail - fixed_total - 6)
        each = int(remain / max(1, len(flex)))
        for c, _, _ in specs:
            tree.column(c, width=fixed.get(c, each), stretch=False)

