    def _fill_result_table(self, kind=None):
        if kind is None:
            kind = self._current_kind()
        tree = self.trees.get(kind)
        if tree is None:
            return
        tree.delete(*tree.get_children())
        self._key_to_item[kind] = {}
        self._key_to_dfidx[kind] = {}
        df = self._table_dfs.get(kind)
        count = self.table_counts[kind]
        if df is None or df.empty:
            count.config(text="ยังไม่มีข้อมูล (โหลดไฟล์ SPSS หรือกด Gen ก่อน)")
            return
        specs = self.TABLE_SPECS[kind]
        cols = [c for c, _, _ in specs]
        if any(c not in df.columns for c in cols):
            count.config(text="ข้อมูลไม่ครบคอลัมน์ที่ต้องการ")
            return
        mode = self.table_filters[kind].get()
        kw = self.table_searches[kind].get().strip().lower()
        idx_list = df.index.tolist()
        rows = df[cols].values.tolist()
        limit = 20000
        shown = 0
        for i, (di, raw) in enumerate(zip(idx_list, rows)):
            vals = [self._cell_text(v) for v in raw]
            key = self._row_key_from_values(kind, vals)
            self._key_to_dfidx[kind][key] = di
            has_eng = vals[-1].strip() != ""
            if mode == "เฉพาะที่มี Eng" and not has_eng:
                continue
            if mode == "เฉพาะที่ยังว่าง" and has_eng:
                continue
            if kw and not any(kw in v.lower() for v in vals):
                continue
            if shown >= limit:
                continue
            tags = ("even" if i % 2 else "odd",) + (() if has_eng else ("missing",))
            self._key_to_item[kind][key] = tree.insert("", "end", values=vals, tags=tags)
            shown += 1
        self._update_count_label(kind)

    def _update_count_label(self, kind):
        df = self._table_dfs.get(kind)
        count = self.table_counts.get(kind)
        if count is None:
            return
        if df is None or df.empty:
            count.config(text="ยังไม่มีข้อมูล")
            return
        eng_col = self.TABLE_SPECS[kind][-1][0]
        total = len(df)
        filled = self._count_filled(df, eng_col)
        shown = len(self.trees[kind].get_children())
        count.config(text=f"แสดง {shown:,} / {total:,} แถว   |   มี Eng {filled:,} แถว   |   ยังว่าง {total - filled:,} แถว")
        self._draw_tabs()

    def _live_update_rows(self, kind, ai_df):
        """เขียนภาษาอังกฤษที่ AI เพิ่งส่งกลับมาลงในตารางทันที (ระหว่าง Gen)"""
        tree = self.trees.get(kind)
        df = self._table_dfs.get(kind)
        if tree is None or df is None or ai_df is None or ai_df.empty:
            return
        src_eng = 'VAR_ENG' if kind == 'jod' else 'Label_EN'
        if src_eng not in ai_df.columns:
            return
        eng_col = self.TABLE_SPECS[kind][-1][0]
        key_cols = ['Name'] if kind == 'jod' else ['Variable', 'Value']
        if any(c not in ai_df.columns for c in key_cols):
            return
        k2i = self._key_to_item.get(kind, {})
        k2d = self._key_to_dfidx.get(kind, {})
        last_item = None
        changed = 0
        for raw in ai_df[key_cols + [src_eng]].values.tolist():
            eng = self._cell_text(raw[-1]).strip()
            if eng == "":
                continue
            key = self._row_key_from_values(kind, [self._cell_text(v) for v in raw[:-1]])
            di = k2d.get(key)
            if di is not None and eng_col in df.columns:
                df.at[di, eng_col] = eng
            item = k2i.get(key)
            if item is not None and tree.exists(item):
                tree.set(item, eng_col, eng)
                tags = tuple(t for t in tree.item(item, "tags") if t != "missing")
                tree.item(item, tags=tags)
                last_item = item
                changed += 1
        if changed:
            self._update_count_label(kind)
            if last_item is not None and self.table_filters[kind].get() == "ทั้งหมด":
                try:
                    tree.see(last_item)
                except Exception:
                    pass

    def _copy_tree_cell(self, event, kind):
        """ดับเบิลคลิกเพื่อคัดลอกข้อความในช่องนั้น"""
        tree = self.trees.get(kind)
        if tree is None:
            return
        row_id = tree.identify_row(event.y)
        col_id = tree.identify_column(event.x)
        if not row_id or not col_id:
            return
        try:
            idx = int(col_id.replace("#", "")) - 1
            text = tree.item(row_id, "values")[idx]
        except Exception:
            return
        if text:
            try:
                pyperclip.copy(text)
                self.table_counts[kind].config(text=f"คัดลอกแล้ว: {text[:70]}")
                self.root.after(2500, lambda k=kind: self._update_count_label(k))
            except Exception:
                pass

