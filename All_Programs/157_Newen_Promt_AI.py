    def _write_excel(self, excel_path, var_df, value_df):
        var_df = var_df.copy()
        value_df = value_df.copy()
        for df, col in ((var_df, 'VAR_ENG'), (value_df, 'Label_EN')):
            if col in df.columns:
                df[col] = df[col].apply(lambda v: "" if pd.isna(v) else v)
        with pd.ExcelWriter(excel_path, engine="openpyxl") as writer:
            var_df.to_excel(writer, index=False, sheet_name='Var')
            value_df.to_excel(writer, index=False, sheet_name='Value')
            # ปรับความกว้างคอลัมน์ให้อ่านง่าย
            for sheet_name, df in (('Var', var_df), ('Value', value_df)):
                ws = writer.sheets[sheet_name]
                for i, col in enumerate(df.columns):
                    try:
                        max_len = max([len(str(col))] + [len(str(v)) for v in df[col].head(500).tolist()])
                    except Exception:
                        max_len = 12
                    ws.column_dimensions[openpyxl.utils.get_column_letter(i + 1)].width = min(max(10, max_len + 2), 90)

