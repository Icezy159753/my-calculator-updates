        tree = self.trees.get(kind)
        items = tree.get_children() if tree else ()
        if not items:
            messagebox.showwarning("ไม่มีข้อมูล", "ยังไม่มีแถวในตารางให้คัดลอก")
            return
        heads = [tree.heading(c, "text") for c in tree["columns"]]
        lines = ["\t".join(heads)] + ["\t".join(str(v) for v in tree.item(i, "values")) for i in items]
        pyperclip.copy("\n".join(lines))
        messagebox.showinfo("คัดลอกสำเร็จ", f"คัดลอกตาราง {len(items):,} แถวแล้ว (วางใน Excel ได้เลย)")

