def _split_table_line(line):
    """คืนค่า list ของเซลล์ ถ้าบรรทัดนี้ดูเป็นแถวตาราง (คั่นด้วยแท็บ หรือ Markdown |) ไม่งั้นคืน None"""
    s = line.rstrip("\r\n")
    if s.strip().startswith("```"):
        return None
    if "\t" in s:
        return [c.strip() for c in s.split("\t")]
    st = s.strip()
    if st.startswith("|") and st.count("|") >= 2:
        inner = st.strip("|")
        cells = [c.strip() for c in inner.split("|")]
        # ข้ามแถวคั่นหัวตารางของ Markdown (|---|---|)
        if all((c == "" or re.fullmatch(r":?-{2,}:?", c)) for c in cells):
            return None
        return cells
    return None


def parse_ai_table(text, col_aliases):
    """
    แปลงข้อความจาก AI ให้เป็น DataFrame ตามคอลัมน์ใน col_aliases (dict: ชื่อคอลัมน์มาตรฐาน -> ชื่อที่ยอมรับ)
    คืนค่า (DataFrame หรือ None, ข้อความอธิบาย)
    """
    target_cols = list(col_aliases.keys())
    rows = []
    for line in text.replace("\r\n", "\n").split("\n"):
        cells = _split_table_line(line)
        if cells is not None:
            rows.append(cells)
    if not rows:
        return None, "ไม่พบแถวที่คั่นด้วยแท็บในผลลัพธ์"

    def match_header(cells):
        low = [c.strip().lower() for c in cells]
        mapping = {}
        for std, aliases in col_aliases.items():
            for i, c in enumerate(low):
                if i in mapping.values():
                    continue
                if c in aliases or c == std.lower():
                    mapping[std] = i
                    break
        return mapping

    header_idx = None
    mapping = {}
    for i, cells in enumerate(rows):
        m = match_header(cells)
        # ต้องเจออย่างน้อย 2 คอลัมน์แรก (Name/VAR_THA หรือ Variable/Value)
        if all(k in m for k in target_cols[:2]):
            header_idx = i
            mapping = m
            break

    if header_idx is None:
        # ไม่มีหัวตาราง: ถ้าจำนวนคอลัมน์ตรงกับที่คาดไว้ ให้ถือว่าเรียงตามลำดับ
        n = len(target_cols)
        candidates = [r for r in rows if len(r) in (n, n - 1)]
        if not candidates:
            return None, "ไม่พบหัวตาราง (" + ", ".join(target_cols) + ") ในผลลัพธ์"
        mapping = {c: i for i, c in enumerate(target_cols)}
        data_rows = candidates
    else:
        data_rows = rows[header_idx + 1:]

    # คอลัมน์ที่ไม่ได้ระบุในหัวตาราง (เช่น AI ไม่ใส่ Label_En) ให้เดาจากลำดับ
    for c in target_cols:
        if c not in mapping:
            used = set(mapping.values())
            for i in range(len(target_cols) + 2):
                if i not in used:
                    mapping[c] = i
                    break

    records = []
    for cells in data_rows:
        # ข้ามหัวตารางที่ซ้ำ
        if all(k in match_header(cells) for k in target_cols[:2]):
            continue
        if all(c == "" for c in cells):
            continue
        rec = {}
        for c in target_cols:
            idx = mapping[c]
            rec[c] = cells[idx] if idx < len(cells) else ""
        if rec[target_cols[0]] == "":
            continue
        records.append(rec)

    if not records:
        return None, "พบหัวตารางแต่ไม่มีข้อมูลแถว"
    return pd.DataFrame(records, columns=target_cols), f"อ่านได้ {len(records)} แถว"


def _norm_value(v):
    """ทำให้ค่า Value เปรียบเทียบกันได้ เช่น 1.0 == 1 == '1'"""
    if v is None:
        return ""
    s = str(v).strip()
    if s == "" or s.lower() in ("nan", "none", "<na>"):
        return ""
    try:
        f = float(s)
        if abs(f - round(f)) < 1e-9:
            return str(int(round(f)))
        return str(f)
    except Exception:
        return s


