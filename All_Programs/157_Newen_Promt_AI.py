def _load_dotenv_file():
    """อ่านไฟล์ .env (ถ้ามี) ที่อยู่โฟลเดอร์เดียวกับโปรแกรม แบบง่าย ๆ"""
    values = {}
    try:
        base_dir = os.path.dirname(os.path.abspath(__file__))
    except NameError:
        base_dir = os.getcwd()
    env_path = os.path.join(base_dir, ".env")
    if os.path.isfile(env_path):
        try:
            with open(env_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#") or "=" not in line:
                        continue
                    k, v = line.split("=", 1)
                    values[k.strip()] = v.strip().strip('"').strip("'")
        except Exception:
            pass
    return values


def _get_ai_config():
    dotenv = _load_dotenv_file()

    def pick(key, default):
        return os.environ.get(key) or dotenv.get(key) or default

    return {
        "base_url": pick("OMNIROUTE_BASE_URL", DEFAULT_BASE_URL),
        "model": pick("OMNIROUTE_MODEL", DEFAULT_MODEL),
        "api_key": _embedded_api_key(),   # ใช้ key ที่ฝังในโปรแกรมเสมอ (ไม่อ่านจาก env/.env)
    }




