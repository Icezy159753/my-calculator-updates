    def _stream_one_request(self, url, headers, prompt, stop_event, on_chunk):
        """เรียก API แบบ stream 1 ครั้ง คืนค่า (ข้อความทั้งหมด, finish_reason). โยน Exception ถ้าล้มเหลว"""
        payload = {
            "model": self._ai_model,
            "messages": [{"role": "user", "content": prompt}],
            "stream": True,
            "temperature": 0,
            "max_tokens": AI_MAX_TOKENS,
        }

        def _post(pl):
            # ส่งเป็น UTF-8 ตรง ๆ (ensure_ascii=False) เพื่อไม่ให้ตัวอักษรไทยบวมเป็น \\uXXXX จน body ใหญ่เกิน
            body = json.dumps(pl, ensure_ascii=False).encode("utf-8")
            return requests.post(url, headers=headers, data=body, stream=True, timeout=(60, 300))

        resp = _post(payload)
        if resp.status_code == 400 and "max_tokens" in resp.text:
            payload.pop("max_tokens", None)
            resp = _post(payload)
        if resp.status_code != 200:
            body = resp.text[:600]
            if "<html" in body.lower():
                body = f"(หน้า HTML จาก Gateway: {resp.reason})"
            try:
                resp.close()
            except Exception:
                pass
            if resp.status_code in (429, 502, 503, 504):
                raise AIBusyError(f"HTTP {resp.status_code} {body[:200]}")
            raise RuntimeError(f"API ตอบกลับ HTTP {resp.status_code} {body}")

        full_text = []
        finish_reason = None
        started = time.time()
        last_content_at = started
        got_done = False
        self._last_from_cache = False
        try:
            # ถอดรหัสเป็น UTF-8 เอง (proxy ไม่ระบุ charset ทำให้ requests เดาเป็น latin-1 แล้วภาษาไทยเพี้ยน)
            for raw_line in resp.iter_lines(decode_unicode=False):
                if stop_event.is_set():
                    break
                if self.ai_deadline_event.is_set():
                    # หมดเวลาตามเพดาน: เก็บที่ได้ไว้แล้วออก
                    finish_reason = "deadline"
                    got_done = True
                    break
                line = raw_line.decode("utf-8", errors="replace") if isinstance(raw_line, bytes) else raw_line
                now = time.time()
                if now - started > AI_REQUEST_DEADLINE:
                    raise AIStreamError(f"เกินเวลา {AI_REQUEST_DEADLINE // 60} นาทีต่อ request", "".join(full_text))
                if now - last_content_at > AI_STALL_SECONDS:
                    raise AIStreamError(f"AI ไม่ส่งเนื้อหาใหม่มานานกว่า {AI_STALL_SECONDS // 60} นาที (ค้าง)", "".join(full_text))
                if not line or not line.startswith("data:"):
                    continue
                data = line[5:].strip()
                if data == "[DONE]":
                    got_done = True
                    break
                try:
                    obj = json.loads(data)
                except Exception:
                    continue
                if isinstance(obj, dict) and str(obj.get("id", "")).startswith("chatcmpl-omniroute-sse"):
                    self._last_from_cache = True   # proxy ตอบจาก cache (prompt ซ้ำกับที่เคยส่ง)
                if isinstance(obj, dict) and obj.get("error"):
                    err = obj["error"]
                    msg = err.get("message") if isinstance(err, dict) else str(err)
                    raise AIStreamError(f"API error: {msg}", "".join(full_text))
                choices = obj.get("choices") or []
                if not choices:
                    continue
                ch0 = choices[0] or {}
                delta = ch0.get("delta") or {}
                content = delta.get("content")
                if content is None and ch0.get("message"):
                    content = (ch0.get("message") or {}).get("content")
                if content:
                    full_text.append(content)
                    last_content_at = time.time()
                    on_chunk(content)
                if ch0.get("finish_reason"):
                    finish_reason = ch0.get("finish_reason")
                    got_done = True
        except AIStreamError:
            raise
        except Exception as e:
            # การเชื่อมต่อหลุดกลางทาง: ส่งข้อความบางส่วนกลับไปด้วย
            raise AIStreamError(f"{type(e).__name__}: {e}", "".join(full_text))
        finally:
            try:
                resp.close()
            except Exception:
                pass
        if not stop_event.is_set() and not got_done and not full_text:
            raise AIStreamError("การเชื่อมต่อจบลงโดยไม่มีเนื้อหา", "")
        if self._last_from_cache or (full_text and time.time() - started < 3 and finish_reason != "deadline"):
            finish_reason = f"{finish_reason or 'stop'}|cache"
        return "".join(full_text), finish_reason

    def _run_job(self, url, headers, job, stop_event):
        """ส่ง 1 ชุด (มี retry) แล้วส่ง event เข้า queue"""
        idx = job["index"]
        self.ai_queue.put(("batch_start", idx, None))
        last_err = None
        result = None
        best_partial = ""
        attempt = 0
        busy_tries = 0
        while attempt < AI_RETRY_PER_BATCH and not stop_event.is_set():
            if self.ai_deadline_event.is_set():
                break
            attempt += 1
            self._admission_acquire(stop_event)
            try:
                text, finish = self._stream_one_request(
                    url, headers, job["prompt"], stop_event,
                    lambda c, i=idx: self.ai_queue.put(("chunk", i, c)))
                result = (text, finish)
                self._admission_release(success=True)
                break
            except AIBusyError as e:
                # proxy ไม่ว่าง: ลดจำนวนที่ส่งพร้อมกันลง แล้วรอส่งใหม่ โดยไม่นับเป็นความล้มเหลวปกติ
                self._admission_release(success=False)
                busy_tries += 1
                last_err = str(e)
                if busy_tries <= AI_BUSY_RETRIES:
                    attempt -= 1
                    wait = min(45, 8 * busy_tries)
                    self.ai_queue.put(("batch_busy", idx, (busy_tries, wait, last_err)))
                    self._sleep_interruptible(wait, stop_event)
                    continue
            except Exception:
                self._admission_release(success=True)
                raise
            except AIStreamError as e:
                last_err = str(e)
                if len(e.partial) > len(best_partial):
                    best_partial = e.partial
            except Exception as e:
                last_err = f"{type(e).__name__}: {e}"
            if attempt < AI_RETRY_PER_BATCH and not stop_event.is_set():
                self.ai_queue.put(("batch_retry", idx, (attempt, last_err)))
                self._sleep_interruptible(5 * attempt, stop_event)
        if stop_event.is_set() and result is None:
            return
        if result is None and self.ai_deadline_event.is_set():
            if best_partial.strip():
                self.ai_queue.put(("batch_done", idx, (best_partial, "deadline")))
            else:
                self.ai_queue.put(("batch_error", idx, "หมดเวลาตามเพดานก่อนได้ผล"))
            return
        if result is None:
            if best_partial.strip():
                # ใช้ผลบางส่วนที่ดีที่สุดแทน (แถวที่ขาดจะเว้นว่างไว้)
                self.ai_queue.put(("batch_done", idx, (best_partial, "partial")))
            else:
                self.ai_queue.put(("batch_error", idx, last_err or "unknown error"))
        else:
            self.ai_queue.put(("batch_done", idx, result))

    # ----- ควบคุมจำนวน request ที่ส่งพร้อมกันแบบปรับตัว (ลดเมื่อ proxy busy, เพิ่มกลับเมื่อสำเร็จ) -----
    def _admission_acquire(self, stop_event):
        while not stop_event.is_set() and not self.ai_deadline_event.is_set():
            with self._adm_lock:
                if self._adm_active < self._adm_limit:
                    self._adm_active += 1
                    return
            time.sleep(0.5)
        with self._adm_lock:
            self._adm_active += 1

    def _admission_release(self, success):
        with self._adm_lock:
            self._adm_active = max(0, self._adm_active - 1)
            if success:
                self._adm_ok_streak += 1
                if self._adm_ok_streak >= 2 and self._adm_limit < self._adm_max:
                    self._adm_limit += 1
                    self._adm_ok_streak = 0
            else:
                self._adm_ok_streak = 0
                self._adm_limit = max(1, min(self._adm_limit - 1, self._adm_active if self._adm_active > 0 else 1))

    @staticmethod
    def _sleep_interruptible(seconds, stop_event):
        end = time.time() + seconds
        while time.time() < end and not stop_event.is_set():
            time.sleep(0.25)

    def _build_jobs(self, kind, batches):
        """สร้าง prompt ของแต่ละชุด (ทำในเธรดเบื้องหลัง) ถ้าชุดไหนต้องบีบแบบสอบถามมากเกินไปจะแบ่งครึ่ง"""
        queue_b = list(batches)
        jobs = []
        while queue_b:
            bdf = queue_b.pop(0)
            self._ctx_tight = False
            prompt = self._build_prompt(kind, bdf)
            if getattr(self, "_ctx_tight", False) and len(bdf) >= 16:
                half = len(bdf) // 2
                queue_b.insert(0, bdf.iloc[half:])
                queue_b.insert(0, bdf.iloc[:half])
                continue
            jobs.append({
                "index": len(jobs),
                "start": int(bdf.index[0]) + 1,
                "end": int(bdf.index[-1]) + 1,
                "rows": len(bdf),
                "prompt": prompt,
            })
        return jobs

    def _ai_worker(self, base_url, model, api_key, kind, batches, stop_event, parallel):
        """ทำงานใน thread แยก: เตรียม prompt แล้วกระจายชุดให้ worker หลายตัวส่งพร้อมกัน"""
        try:
            self._ai_worker_body(base_url, model, api_key, kind, batches, stop_event, parallel)
        except Exception as e:
            self.ai_queue.put(("worker_error", None, f"{type(e).__name__}: {e}"))
            self.ai_queue.put(("all_done", None, None))

    def _ai_worker_body(self, base_url, model, api_key, kind, batches, stop_event, parallel):
        t_prep = time.time()
        jobs = self._build_jobs(kind, batches)
        self.ai_queue.put(("jobs_ready", None, (jobs, time.time() - t_prep)))
        if stop_event.is_set() or self.ai_deadline_event.is_set():
            self.ai_queue.put(("stopped" if stop_event.is_set() else "all_done", None, None))
            return
        url = base_url.rstrip("/") + "/chat/completions"
        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json; charset=utf-8",
            "Accept": "text/event-stream",
        }
        self._ai_model = model
        pending = list(jobs)
        lock = threading.Lock()
        self._adm_lock = threading.Lock()
        self._adm_max = max(1, min(parallel, len(jobs)))
        self._adm_limit = self._adm_max
        self._adm_active = 0
        self._adm_ok_streak = 0

        def runner(delay):
            time.sleep(delay)
            while not stop_event.is_set() and not self.ai_deadline_event.is_set():
                with lock:
                    if not pending:
                        return
                    job = pending.pop(0)
                self._run_job(url, headers, job, stop_event)

        n_threads = max(1, min(parallel, len(jobs)))
        threads = [threading.Thread(target=runner, args=(i * 1.5,), daemon=True) for i in range(n_threads)]
        for t in threads:
            t.start()
        for t in threads:
            t.join()
        self.ai_queue.put(("stopped" if stop_event.is_set() else "all_done", None, None))

    # ----- ส่วนแสดงผล (main thread) -----
    def _poll_ai_queue(self):
        """ทำงานใน main thread: ดึง event จาก queue มาอัปเดต UI (แสดงผลเรียงตามลำดับชุด)"""
        try:
            finished = None
            while True:
                try:
                    kind, idx, payload = self.ai_queue.get_nowait()
                except queue.Empty:
                    break
                if kind == "chunk":
                    self.ai_char_count += len(payload)
                    if idx == self._display_idx:
                        self._show_batch_header(idx)
                        self._append_output(payload)
                    else:
                        self._buf.setdefault(idx, []).append(payload)
                elif kind == "worker_error":
                    self.log(f"เกิดข้อผิดพลาดในเบื้องหลัง: {str(payload)[:160]}", "err")
                elif kind == "jobs_ready":
                    jobs, prep_sec = payload
                    self.ai_jobs = jobs
                    self.ai_batch_total = len(jobs)
                    self.log(f"เตรียมข้อมูลเสร็จ {len(jobs)} ชุด ({prep_sec:.1f} วินาที) เริ่มส่งให้ AI")
                elif kind == "batch_start":
                    self._active.add(idx)
                    if idx == self._display_idx:
                        self._show_batch_header(idx)
                elif kind == "batch_retry":
                    attempt, err = payload
                    self.log(f"ชุดที่ {idx + 1} ล้มเหลว (ครั้งที่ {attempt}): {err[:110]} - กำลังลองใหม่", "err")
                    self._buf[idx] = []   # ทิ้งข้อความของรอบที่ล้มเหลว
                elif kind == "batch_busy":
                    tries, wait, err = payload
                    self.log(f"ชุดที่ {idx + 1}: AI ไม่ว่าง รอ {wait} วินาทีแล้วส่งใหม่ (ครั้งที่ {tries})", "warn")
                elif kind in ("batch_done", "batch_error"):
                    self._active.discard(idx)
                    self._done[idx] = (kind, payload)
                    self._collect_batch_result(idx, kind, payload)
                    self._advance_display()
                elif kind in ("all_done", "stopped"):
                    finished = kind
                    break
            if self.ai_is_running:
                self._update_running_status()
            if finished is not None:
                self._advance_display(force=True)
                self._on_ai_finished(finished)
        finally:
            self.root.after(60, self._poll_ai_queue)

    def _show_batch_header(self, idx):
        if idx in self._header_shown or self.ai_batch_total == 0:
            return
        self._header_shown.add(idx)
        job = self.ai_jobs[idx] if idx < len(self.ai_jobs) else None
        if job:
            self.log(f"ส่งชุดที่ {idx + 1}/{self.ai_batch_total} (แถว {job['start']:,}-{job['end']:,}, {job['rows']} แถว, prompt {len(job['prompt']):,} ตัวอักษร)")
        self.output_text.insert(tk.END, f"\n===== ชุดที่ {idx + 1}/{self.ai_batch_total} =====\n")
        # ข้อความที่รอไว้ของชุดนี้
        if idx in self._buf:
            self._append_output("".join(self._buf.pop(idx)))

    def _append_output(self, text):
        self.output_text.insert(tk.END, text)
        self.output_text.see(tk.END)

    def _collect_batch_result(self, idx, kind, payload):
        gen_type = self.current_gen_type
        aliases = self._aliases_for(gen_type)
        if kind == "batch_error":
            self.ai_batch_failed.append(idx + 1)
            self._done[idx] = ("batch_error", payload)
            return
        text, finish = payload
        finish = finish or ""
        if "|cache" in finish:
            self.ai_cache_hits = getattr(self, "ai_cache_hits", 0) + 1
        self.ai_raw_parts.append(text)
        df, note = parse_ai_table(text, aliases)
        if df is not None:
            self.ai_batch_parsed.append(df)
            got = len(df)
            try:
                self._live_update_rows(gen_type, df)
            except Exception:
                pass
        else:
            got = 0
            self.ai_batch_failed.append(idx + 1)
        self._done[idx] = ("batch_done", (got, finish, note))

    def _advance_display(self, force=False):
        """เลื่อนคิวแสดงผลไปยังชุดถัดไปเมื่อชุดปัจจุบันเสร็จแล้ว"""
        while self._display_idx in self._done:
            idx = self._display_idx
            self._show_batch_header(idx)
            kind, info = self._done[idx]
            if kind == "batch_error":
                self.log(f"ชุดที่ {idx + 1}/{self.ai_batch_total} ล้มเหลวถาวร: {str(info)[:160]}", "err")
            else:
                got, finish, note = info
                finish = finish or ""
                cache = " ⚡ ตอบจาก cache ของ proxy (prompt ซ้ำกับที่เคยส่ง)" if "|cache" in finish else ""
                finish = finish.replace("|cache", "")
                trunc = ""
                if finish == "length":
                    trunc = " ⚠ ถูกตัด (ยาวเกิน)"
                elif finish == "partial":
                    trunc = " ⚠ ได้บางส่วน (การเชื่อมต่อหลุด)"
                elif finish == "deadline":
                    trunc = " ⏱ หมดเวลาตามเพดาน (เก็บที่ได้ไว้)"
                elif got == 0:
                    trunc = f" ⚠ {note}"
                trunc += cache
                self.log(f"ชุดที่ {idx + 1}/{self.ai_batch_total} เสร็จ: เขียนลงตาราง {got} แถว{trunc}",
                         "ok" if got and not trunc else "warn")
            self._display_idx += 1
            if self._display_idx in self._active or self._display_idx in self._buf:
                self._show_batch_header(self._display_idx)
        if force:
            # แสดงข้อความที่ค้างของชุดที่ยังไม่เสร็จ (กรณีหยุดกลางคัน)
            for idx in sorted(self._buf.keys()):
                self._show_batch_header(idx)

    def _update_running_status(self):
        total = self.ai_batch_total
        if total == 0:
            return
        elapsed = time.time() - (self.ai_started_at or time.time())
        done_n = len(self._done)
        active = ", ".join(str(i + 1) for i in sorted(self._active))
        remain_txt = f" | รอบที่ {self.ai_pass_no}" if self.ai_pass_no > 1 else ""
        if self.ai_deadline_at:
            remain = self.ai_deadline_at - time.time()
            if remain <= 0 and not self.ai_deadline_event.is_set():
                self.ai_deadline_event.set()
            if self.ai_deadline_event.is_set():
                remain_txt = " | ⏱ หมดเวลา กำลังเก็บผลที่ได้..."
            else:
                remain_txt = f" | เหลือเวลา {int(remain // 60)}:{int(remain % 60):02d}"
        txt = (f"สถานะ AI: เสร็จ {done_n}/{total} ชุด | กำลังทำชุดที่ {active or '-'} | "
               f"รับแล้ว {self.ai_char_count:,} ตัวอักษร | {elapsed:,.0f} วินาที{remain_txt}")
        if txt != self._last_status_text:
            self._last_status_text = txt
            self.label_ai_status.config(text=txt, foreground=self.WARNING_COLOR)

    def _on_ai_finished(self, kind):
        elapsed = time.time() - (self.ai_started_at or time.time())
        gen_type = self.current_gen_type
        label = "โจทย์ (Var)" if gen_type == 'jod' else "Code (Value)"
        stopped = (kind == "stopped")
        timed_out = self.ai_deadline_event.is_set()

        # --- ทำต่อเองจนจบ: ส่งซ้ำเฉพาะแถวที่ยังขาด โดยผู้ใช้ไม่ต้องกด Gen ใหม่ ---
        if not stopped and not timed_out and self.ai_batch_parsed and self.ai_pass_no < AI_MAX_PASSES:
            missing_df = self._missing_rows_df(gen_type)
            n_missing = 0 if missing_df is None else len(missing_df)
            prev_missing = getattr(self, "_prev_missing", None)
            time_ok = (self.ai_deadline_at is None) or (self.ai_deadline_at - time.time() > 30)
            progressed = (prev_missing is None) or (n_missing < prev_missing)
            if n_missing > 0 and time_ok and progressed:
                self._prev_missing = n_missing
                self.log(f"ยังขาด {n_missing:,} แถว - ทำต่อเองรอบที่ {self.ai_pass_no + 1} (ไม่ต้องกด Gen ซ้ำ)", "warn")
                self._launch_pass(gen_type, missing_df)
                return
            if n_missing > 0 and not progressed:
                self.log(f"ยังขาด {n_missing:,} แถว แต่รอบล่าสุดไม่คืบหน้าแล้ว จึงหยุด "
                         f"(แถวเหล่านี้น่าจะไม่มีคู่ภาษาอังกฤษในแบบสอบถาม)", "warn")

        self.ai_is_running = False
        self._set_ai_buttons_running(False)
        self.ai_deadline_at = None

        if not self.ai_batch_parsed and not self.ai_direct_idx and self.ai_continue_prev is None:
            msg = "หยุดโดยผู้ใช้ก่อนได้ผลลัพธ์" if stopped else "ไม่มีชุดใดที่อ่านตารางได้"
            self.label_ai_status.config(text=f"สถานะ AI: {label} - {msg} ({elapsed:,.0f} วินาที)", foreground=self.DESTRUCTIVE_COLOR)
            self.label_output_title.config(text=f"ผลลัพธ์ AI {label} ({msg})")
            if not stopped:
                messagebox.showwarning("อ่านผลลัพธ์ไม่ได้",
                                       "AI ตอบกลับแล้ว แต่แปลงเป็นตารางไม่ได้\n"
                                       "ลองกด Gen ใหม่อีกครั้ง หรือคัดลอกข้อความไปจัดการเอง")
            self._update_summary_label()
            self.ai_times[gen_type] = elapsed
            self.log(f"{label}: {msg} ({self._fmt_secs(elapsed)})", "err")
            self._finish_or_chain(gen_type, stopped)
            return

        if self.ai_batch_parsed:
            ai_df = pd.concat(self.ai_batch_parsed, ignore_index=True)
        else:
            cols = list(VAR_COL_ALIASES.keys()) if gen_type == 'jod' else list(VALUE_COL_ALIASES.keys())
            ai_df = pd.DataFrame(columns=cols)

        if gen_type == 'jod':
            self.ai_raw_var_text = "\n".join(self.ai_raw_parts)
            merged, matched = self._merge_var_result(ai_df)
            src_col, out_col = 'VAR_THA', 'VAR_ENG'
        else:
            self.ai_raw_value_text = "\n".join(self.ai_raw_parts)
            merged, matched = self._merge_value_result(ai_df)
            src_col, out_col = 'Label', 'Label_EN'

        # ทำต่อจากรอบก่อน: แถวที่รอบนี้ไม่ได้ส่ง ให้ใช้ผลรอบก่อน
        if self.ai_continue_prev is not None and out_col in self.ai_continue_prev.columns:
            prev_col = self.ai_continue_prev[out_col].reindex(merged.index)
            merged[out_col] = merged[out_col].where(merged[out_col].notna(), prev_col)
            matched = int(merged.loc[[i for i in merged.index if i not in self.ai_direct_idx], out_col].notna().sum())
            self.ai_continue_prev = None

        # เติมให้สม่ำเสมอ (Value): แถวที่ AI เว้นว่าง แต่มีแถวอื่นที่ข้อความไทยตรงกันเป๊ะและ AI เติม Eng ไว้แล้ว
        consist_n = 0
        if gen_type == 'code':
            consist_n = self._fill_consistent_values(merged, src_col, out_col)

        # แถวที่ไม่มีภาษาไทย: ใช้ข้อความเดิมเป็น Eng
        direct_n = 0
        if self.ai_direct_idx:
            for i in self.ai_direct_idx:
                if i in merged.index and pd.isna(merged.at[i, out_col]):
                    v = merged.at[i, src_col]
                    merged.at[i, out_col] = "" if pd.isna(v) else str(v)
                    direct_n += 1
        missing_n = int(merged[out_col].isna().sum())

        if gen_type == 'jod':
            self.ai_result_var_df = merged
            total_rows = len(self.spss_df_var)
        else:
            self.ai_result_value_df = merged
            total_rows = len(self.spss_df_value)
        filled = self._count_filled(merged, out_col)
        ai_rows = total_rows - len(self.ai_direct_idx)

        summary = f"AI จับคู่ได้ {matched}/{ai_rows} แถว, ใช้ค่าเดิม {direct_n} แถว, มี Eng รวม {filled}/{total_rows} แถว"
        if consist_n:
            summary += f" (เติมตามข้อความไทยที่ตรงกัน {consist_n} แถว)"
        if self.ai_pass_no > 1:
            summary += f" (ทำต่อเอง {self.ai_pass_no} รอบ)"
        cache_hits = getattr(self, "ai_cache_hits", 0)
        if cache_hits:
            summary += f" ⚡ {cache_hits}/{self.ai_batch_total} ชุดตอบจาก cache ของ proxy (เวลาที่เห็นไม่ใช่เวลาจริง)"
        warn = ""
        if self.ai_batch_failed:
            warn += f" ⚠ ชุดที่ล้มเหลว: {', '.join(str(i) for i in sorted(set(self.ai_batch_failed)))}"
        if stopped:
            warn += " ⚠ หยุดก่อนครบทุกชุด"
        if timed_out:
            warn += " ⏱ ถึงเพดานเวลา"
        if missing_n:
            warn += f" ⚠ ยังขาด {missing_n} แถวที่ไม่มีคู่ในแบบสอบถาม (ตอนบันทึก SPSS จะคงข้อความเดิม)"

        self.label_ai_status.config(
            text=f"สถานะ AI: {label} เสร็จแล้ว ({elapsed:,.0f} วินาที) - {summary}{warn}",
            foreground=self.WARNING_COLOR if warn else self.SUCCESS_COLOR)
        self.label_output_title.config(text=f"ผลลัพธ์ AI {label} - {summary}{warn}")

        self.btn_export_eng_excel.config(state="normal")
        self.btn_save_spss.config(state="normal")
        self._update_summary_label()
        self.show_result_table(gen_type, merged)
        self._select_tab(gen_type)
        self.ai_times[gen_type] = elapsed
        self.log(f"{label} เสร็จแล้ว ใช้เวลา {self._fmt_secs(elapsed)} - {summary}{warn}",
                 "warn" if warn else "ok")
        self._finish_or_chain(gen_type, stopped)

    @staticmethod
    def _fill_consistent_values(merged, src_col, out_col):
        """แถวที่ Eng ว่าง/ไม่ได้ส่งกลับ แต่มีแถวอื่นที่ข้อความไทย (normalize แล้ว) ตรงกันเป๊ะและมี Eng อยู่แล้ว
        ให้ใช้ Eng เดียวกัน เฉพาะเมื่อข้อความไทยนั้นถูกจับคู่กับ Eng เพียงแบบเดียวเท่านั้น"""
        def nk(v):
            return re.sub(r'\s+', ' ', str(v)).strip().lower()
        eng_by_thai = {}
        for th_v, en_v in zip(merged[src_col], merged[out_col]):
            if pd.isna(th_v) or pd.isna(en_v) or str(en_v).strip() == "" or not THAI_RE.search(str(th_v)):
                continue
            eng_by_thai.setdefault(nk(th_v), set()).add(str(en_v).strip())
        filled = 0
        for i in merged.index:
            en_v = merged.at[i, out_col]
            if not (pd.isna(en_v) or str(en_v).strip() == ""):
                continue
            th_v = merged.at[i, src_col]
            if pd.isna(th_v):
                continue
            cands = eng_by_thai.get(nk(th_v))
            if cands and len(cands) == 1:
                merged.at[i, out_col] = next(iter(cands))
                filled += 1
        return filled

    def _missing_rows_df(self, kind):
        """แถวที่ต้องส่ง AI แต่ยังไม่มีผลกลับมา (จากทุกรอบที่ผ่านมา)"""
        src_df = self.spss_df_var if kind == 'jod' else self.spss_df_value
        ai_df = pd.concat(self.ai_batch_parsed, ignore_index=True) if self.ai_batch_parsed else None
        if ai_df is None:
            return None
        merged, _ = (self._merge_var_result(ai_df) if kind == 'jod' else self._merge_value_result(ai_df))
        out_col = 'VAR_ENG' if kind == 'jod' else 'Label_EN'
        need = [i for i in src_df.index if i not in set(self.ai_direct_idx)]
        if self.ai_continue_prev is not None and out_col in self.ai_continue_prev.columns:
            prev_col = self.ai_continue_prev[out_col].reindex(merged.index)
            merged[out_col] = merged[out_col].where(merged[out_col].notna(), prev_col)
        missing_idx = [i for i in need if pd.isna(merged.at[i, out_col])]
        return src_df.loc[missing_idx]

    def _finish_or_chain(self, gen_type, stopped):
        """โหมดต่อเนื่อง: จบ Var แล้วเริ่ม Value ต่อ / ถ้าจบครบแล้วสรุปเวลาทั้งหมด"""
        if not getattr(self, "ai_chain", False):
            return
        if stopped:
            self.ai_chain = False
            self.log("หยุดโดยผู้ใช้ จึงไม่ทำ Code (Value) ต่อ", "warn")
            return
        if gen_type == 'jod':
            self.log("เริ่ม Code (Value) ต่ออัตโนมัติ (จับเวลาใหม่)", "head")
            self.root.after(600, lambda: self.start_ai_generation('code', from_chain=True))
            return
        # จบครบทั้งสองงาน
        self.ai_chain = False
        t_var = self.ai_times.get('jod') or 0
        t_val = self.ai_times.get('code') or 0
        total = t_var + t_val
        msg = (f"เสร็จทั้งหมด | โจทย์ (Var) {self._fmt_secs(t_var)} | "
               f"Code (Value) {self._fmt_secs(t_val)} | รวม {self._fmt_secs(total)}")
        self.log("=== " + msg + " ===", "head")
        self.label_ai_status.config(text="สถานะ AI: " + msg, foreground=self.SUCCESS_COLOR)
        messagebox.showinfo("Gen ต่อเนื่องเสร็จแล้ว",
                            f"โจทย์ (Var): {self._fmt_secs(t_var)}\n"
                            f"Code (Value): {self._fmt_secs(t_val)}\n"
                            f"รวมทั้งหมด: {self._fmt_secs(total)}")

    def _merge_var_result(self, ai_df):
        """รวม VAR_ENG จาก AI เข้ากับตาราง Var ต้นฉบับ (จับคู่ด้วย Name)"""
        eng_map = {}
        for _, r in ai_df.iterrows():
            name = str(r['Name']).strip()
            eng = str(r['VAR_ENG']).strip() if not pd.isna(r['VAR_ENG']) else ""
            if name and name not in eng_map:
                eng_map[name] = eng
        # เผื่อ AI พิมพ์ชื่อตัวแปรต่างตัวพิมพ์
        eng_map_lower = {k.lower(): v for k, v in eng_map.items()}

        merged = self.spss_df_var.copy()
        matched = 0
        out = []
        for name in merged['Name']:
            key = str(name).strip()
            if key in eng_map:
                out.append(eng_map[key]); matched += 1
            elif key.lower() in eng_map_lower:
                out.append(eng_map_lower[key.lower()]); matched += 1
            else:
                out.append(pd.NA)   # AI ไม่ได้ส่งแถวนี้กลับมา (ต่างจาก "" = AI ส่งค่าว่าง)
        merged['VAR_ENG'] = pd.Series(out, index=merged.index, dtype=object)
        return merged, matched

    def _merge_value_result(self, ai_df):
        """รวม Label_EN จาก AI เข้ากับตาราง Value ต้นฉบับ (จับคู่ด้วย Variable + Value)"""
        eng_map = {}
        for _, r in ai_df.iterrows():
            var = str(r['Variable']).strip()
            val = _norm_value(r['Value'])
            eng = str(r['Label_EN']).strip() if not pd.isna(r['Label_EN']) else ""
            if var:
                eng_map.setdefault((var.lower(), val), eng)

        merged = self.spss_df_value.copy()
        matched = 0
        out = []
        for var, val in zip(merged['Variable'], merged['Value']):
            key = (str(var).strip().lower(), _norm_value(val))
            if key in eng_map:
                out.append(eng_map[key]); matched += 1
            else:
                out.append(pd.NA)   # AI ไม่ได้ส่งแถวนี้กลับมา (ต่างจาก "" = AI ส่งค่าว่าง)
        merged['Label_EN'] = pd.Series(out, index=merged.index, dtype=object)
        return merged, matched

    def _update_summary_label(self):
        def part(df, col, total, name):
            if df is None:
                return f"{name} - ยังไม่ได้ Gen"
            return f"{name} - แปะ Eng {self._count_filled(df, col)}/{len(df)} แถว"
        n_var = len(self.spss_df_var) if self.spss_df_var is not None else 0
        n_val = len(self.spss_df_value) if self.spss_df_value is not None else 0
        txt = ("ผลลัพธ์: " + part(self.ai_result_var_df, 'VAR_ENG', n_var, "โจทย์ (Var)")
               + "   |   " + part(self.ai_result_value_df, 'Label_EN', n_val, "Code (Value)"))
        ready = self.ai_result_var_df is not None or self.ai_result_value_df is not None
        self.label_ai_summary.config(text=txt, foreground=self.SUCCESS_COLOR if ready else self.WARNING_COLOR)

    # -----------------------------------------------------------------
    #  บันทึกลง SPSS
    # -----------------------------------------------------------------
    def save_labels_to_spss(self):
        if self.ai_is_running:
            messagebox.showwarning("AI กำลังทำงาน", "กรุณารอให้ AI Gen เสร็จ หรือกดหยุดก่อน")
            return
        try:
            import pyspssio
        except Exception:
            messagebox.showerror("ไลบรารีไม่พร้อม",
                                 "ไม่พบโมดูล 'pyspssio'\n\nติดตั้งด้วยคำสั่ง:\n  python -m pip install pyspssio")
            return
        if self.spss_meta is None:
            messagebox.showerror("ไม่มีข้อมูล", "กรุณาโหลดไฟล์ SPSS ก่อนครับ")
            return

        update_var_df = self.ai_result_var_df
        update_value_df = self.ai_result_value_df

        def find_col(df, names):
            for name in names:
                for col in df.columns:
                    if str(col).lower() == str(name).lower():
                        return col
            return None

        def _coerce_value_type(val, var, value_labels, meta):
            if var in value_labels and len(value_labels[var]) > 0:
                sample_key = next(iter(value_labels[var].keys()))
                try:
                    if isinstance(sample_key, int):
                        return int(float(val))
                    elif isinstance(sample_key, float):
                        return float(val)
                    else:
                        return str(val)
                except Exception:
                    return sample_key.__class__(val)
            try:
                is_numeric = (self.spss_meta.variable_types.get(var, 0) == 0)
            except Exception:
                is_numeric = True
            if is_numeric:
                f = float(val)
                return int(f) if abs(f - int(f)) < 1e-9 else f
            return str(val)

        # รองรับกรณีวางผลลัพธ์ TSV ในกล่องข้อความเอง (ทางเลือกเดิม)
        if update_var_df is None and update_value_df is None:
            ai_output_text = self.output_text.get("1.0", tk.END).strip()
            if ai_output_text and self.last_prompt_type:
                if self.last_prompt_type == "jod":
                    df, note = parse_ai_table(ai_output_text, self._aliases_for('jod'))
                    if df is not None:
                        update_var_df, _ = self._merge_var_result(df)
                else:
                    df, note = parse_ai_table(ai_output_text, self._aliases_for('code'))
                    if df is not None:
                        update_value_df, _ = self._merge_value_result(df)
                if update_var_df is None and update_value_df is None:
                    messagebox.showerror("Parse Error", f"อ่านข้อมูลจากกล่องข้อความไม่สำเร็จ:\n{note}")
                    return

        if update_var_df is None and update_value_df is None:
            messagebox.showerror("ไม่มีข้อมูล", "กรุณา Gen ด้วย AI หรือโหลดไฟล์ Excel ผลลัพธ์ก่อน")
            return

        delimiter = self.ma_var.get()
        meta = self.spss_meta
        blank_deletes = bool(self.blank_deletes.get())

        try:
            original_columns = list(meta.column_names)
            df_to_save = self.original_spss_df[original_columns].copy()
        except KeyError as e:
            messagebox.showerror("เกิดข้อผิดพลาด", f"ไม่พบคอลัมน์: {e}")
            return

        new_var_labels_list = list(meta.column_labels)
        new_value_labels = {k: dict(v) for k, v in meta.variable_value_labels.items()}

        # ====== อัปเดต Value Labels ======
        if update_value_df is not None:
            lbl_en_col = find_col(update_value_df, ["Label_EN", "Label_En", "label_en"])
            if not lbl_en_col:
                messagebox.showerror("ไม่พบคอลัมน์", "ไม่พบ 'Label_EN' ในชีท Value")
                return

            for _, r in update_value_df.iterrows():
                var = r.get("Variable")
                val = r.get("Value")
                en_raw = r.get(lbl_en_col)

                if var not in df_to_save.columns:
                    continue
                if pd.isna(val) or str(val).strip() == "":
                    continue
                if pd.isna(en_raw):
                    # AI ไม่ได้ส่งแถวนี้กลับมา: คง label เดิมไว้
                    continue

                en = str(en_raw).strip()
                try:
                    vv = _coerce_value_type(val, var, new_value_labels, meta)
                except Exception:
                    continue

                # นโยบาย "ลบ" label: ว่าง (ถ้าติ๊กเลือก) หรือกำหนดพิเศษ <<DEL>> / <<DELETE>>
                is_delete = en.upper() in {"<<DEL>>", "<<DELETE>>"}
                if en == "" and not blank_deletes:
                    continue
                if en == "" or is_delete:
                    if var in new_value_labels and vv in new_value_labels[var]:
                        del new_value_labels[var][vv]
                    continue

                new_value_labels.setdefault(var, {})
                new_value_labels[var][vv] = en

            # === ทำให้ Value labels ของชุด MA (_O1,_O2,...) เหมือนกันทุกตัว ===
            if delimiter:
                vars_with_ma = [v for v in df_to_save.columns
                                if re.search(rf'{re.escape(delimiter)}\d+$', v)]
                groups = {}
                for v in vars_with_ma:
                    base = v.rsplit(delimiter, 1)[0]
                    groups.setdefault(base, []).append(v)

                for base, members in groups.items():
                    prefer_key = f"{base}{delimiter}1"
                    src_key = None
                    if prefer_key in new_value_labels and new_value_labels[prefer_key]:
                        src_key = prefer_key
                    else:
                        for m in members:
                            if m in new_value_labels and new_value_labels[m]:
                                src_key = m
                                break
                    if not src_key:
                        continue
                    src = dict(new_value_labels[src_key])
                    for m in members:
                        new_value_labels[m] = dict(src)

        # ====== อัปเดต Variable Labels (ENG) ถ้ามี ======
        if update_var_df is not None:
            eng_col = find_col(update_var_df, ["VAR_ENG", "Var_Eng", "var_eng"])
            if not eng_col:
                messagebox.showerror("ไม่พบคอลัมน์", "ไม่พบ 'VAR_ENG' ในชีท Var")
                return
            for _, r in update_var_df.iterrows():
                name, eng = r.get("Name"), r.get(eng_col, None)
                if pd.isna(eng) or name not in original_columns:
                    continue
                eng = str(eng).strip()
                if eng == "" and not blank_deletes:
                    continue
                idx = original_columns.index(name)
                new_var_labels_list[idx] = eng

        # กระจาย var label ของ MA ให้ชุดเดียวกันเท่ากัน (อ้างอิงจาก {base}{delimiter}1)
        if delimiter:
            bases = {v.rsplit(delimiter, 1)[0]
                     for v in df_to_save.columns
                     if re.search(rf'{re.escape(delimiter)}\d+$', v)}
            for base in bases:
                key = f"{base}{delimiter}1"
                if key in original_columns:
                    idx = original_columns.index(key)
                    lbl = new_var_labels_list[idx]
                    if pd.notna(lbl) and lbl != "":
                        for v in [vv for vv in df_to_save.columns
                                  if re.search(rf'^{re.escape(base)}{re.escape(delimiter)}\d+$', vv)]:
                            new_var_labels_list[original_columns.index(v)] = lbl

        var_labels = {c: ("" if pd.isna(l) else str(l))
                      for c, l in zip(original_columns, new_var_labels_list)}
        meta_out = {"var_labels": var_labels, "var_value_labels": new_value_labels}

        default_name = "output_ENG.sav"
        if self.spss_filepath:
            default_name = os.path.splitext(os.path.basename(self.spss_filepath))[0] + "_ENG.sav"
        new_file = filedialog.asksaveasfilename(
            parent=self.root, title="บันทึกไฟล์ SPSS ใหม่ (pyspssio)",
            defaultextension=".sav", initialfile=default_name,
            filetypes=[("SPSS Files", "*.sav"), ("All Files", "*.*")]
        )
        if not new_file:
            return

        try:
            pyspssio.write_sav(new_file, df_to_save, metadata=meta_out)
            self.log(f"บันทึก SPSS: {os.path.basename(new_file)}", "ok")
            messagebox.showinfo("บันทึกสำเร็จ", f"ไฟล์ถูกบันทึกเรียบร้อยแล้ว\n\n{new_file}")
        except Exception as e:
            messagebox.showerror("บันทึกไม่สำเร็จ", f"เขียนไฟล์ด้วย pyspssio ไม่สำเร็จ:\n{e}")

