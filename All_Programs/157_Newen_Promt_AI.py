class RoundButton(tk.Canvas):
    """ปุ่มมุมโค้งวาดด้วย Canvas (ใช้แทน ttk.Button เพื่อไม่ให้ขอบเป็นเหลี่ยม)"""
    default_font = None

    def __init__(self, master, text="", command=None, state="normal",
                 style='Neutral.TButton', font=None, radius=15,
                 padx=18, pady=11, parent_bg=None, **kw):
        bg, fg, hover, dis_bg, dis_fg = BTN_STYLES.get(style, BTN_STYLES['Neutral.TButton'])
        self._bg, self._fg, self._hover_bg = bg, fg, hover
        self._dis_bg, self._dis_fg = dis_bg, dis_fg
        self._text = text
        self._command = command
        self._state = state
        self._radius = radius
        self._hovering = False
        self._font = font or RoundButton.default_font or tkFont.Font(family="Tahoma", size=10, weight="bold")
        super().__init__(master, highlightthickness=0, bd=0,
                         bg=(parent_bg or THEME['frame']), takefocus=0, **kw)
        f = tkFont.Font(font=self._font)
        tk.Canvas.configure(self, width=f.measure(text) + padx * 2,
                            height=f.metrics("linespace") + pady * 2)
        self.bind("<Configure>", lambda e: self._draw())
        self.bind("<Enter>", self._on_enter)
        self.bind("<Leave>", self._on_leave)
        self.bind("<ButtonPress-1>", self._on_press)
        self.bind("<ButtonRelease-1>", self._on_release)
        self._draw()

    # ----- วาด -----
    def _draw(self):
        self.delete("all")
        w = max(self.winfo_width(), 2)
        h = max(self.winfo_height(), 2)
        if self._state == "disabled":
            bg, fg = self._dis_bg, self._dis_fg
        elif self._hovering:
            bg, fg = self._hover_bg, self._fg
        else:
            bg, fg = self._bg, self._fg
        r = max(2, min(self._radius, h // 2))
        pts = [r, 0, w - r, 0, w, 0, w, r, w, h - r, w, h,
               w - r, h, r, h, 0, h, 0, h - r, 0, r, 0, 0]
        self.create_polygon(pts, smooth=True, fill=bg, outline="")
        self.create_text(w / 2, h / 2 + 1, text=self._text, fill=fg, font=self._font)

    # ----- เหตุการณ์ -----
    def _on_enter(self, _=None):
        if self._state != "disabled":
            self._hovering = True
            self.configure(cursor="hand2")
            self._draw()

    def _on_leave(self, _=None):
        self._hovering = False
        self.configure(cursor="")
        self._draw()

    def _on_press(self, _=None):
        if self._state != "disabled":
            self._draw()

    def _on_release(self, event=None):
        if self._state == "disabled" or self._command is None:
            return
        if event is not None and not (0 <= event.x <= self.winfo_width() and 0 <= event.y <= self.winfo_height()):
            return
        self._command()

    # ----- ให้ใช้ .config(state=...) / .config(text=...) ได้เหมือน ttk.Button -----
    def configure(self, cnf=None, **kw):
        redraw = False
        if "state" in kw:
            self._state = kw.pop("state")
            self._hovering = False
            redraw = True
        if "text" in kw:
            self._text = kw.pop("text")
            redraw = True
        if "command" in kw:
            self._command = kw.pop("command")
        if "style" in kw:
            st = kw.pop("style")
            self._bg, self._fg, self._hover_bg, self._dis_bg, self._dis_fg = \
                BTN_STYLES.get(st, BTN_STYLES['Neutral.TButton'])
            redraw = True
        if cnf or kw:
            tk.Canvas.configure(self, cnf, **kw)
        if redraw:
            self._draw()

    config = configure

    def cget(self, key):
        if key == "text":
            return self._text
        if key == "state":
            return self._state
        return tk.Canvas.cget(self, key)


