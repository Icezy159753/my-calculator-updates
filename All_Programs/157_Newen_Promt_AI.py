    @staticmethod
    def _cell_text(v):
        if v is None:
            return ""
        try:
            if pd.isna(v):
                return ""
        except Exception:
            pass
        if isinstance(v, float) and abs(v - int(v)) < 1e-9:
            return str(int(v))
        return str(v)

