    @staticmethod
    def _style_scrollbar(scrolled_widget):
        """ทำสกรอลล์บาร์ของ ScrolledText ให้เข้ากับธีมสว่าง"""
        try:
            scrolled_widget.vbar.configure(bg=THEME['neutral'], troughcolor=THEME['bg'],
                                           activebackground=THEME['neutral_h'], highlightthickness=0,
                                           bd=0, relief="flat", width=12)
        except Exception:
            pass

    def log(self, msg, level=None):
        box = getattr(self, "log_text", None)
        if box is None:
            return
        try:
            box.configure(state="normal")
            box.insert(tk.END, f"[{time.strftime('%H:%M:%S')}] {msg}\n", (level,) if level else ())
            n = int(box.index('end-1c').split('.')[0])
            if n > 900:
                box.delete("1.0", f"{n - 800}.0")
            box.see(tk.END)
            box.configure(state="disabled")
        except Exception:
            pass

    def clear_log(self):
        box = getattr(self, "log_text", None)
        if box is None:
            return
        box.configure(state="normal")
        box.delete("1.0", tk.END)
        box.configure(state="disabled")

    def copy_log(self):
        box = getattr(self, "log_text", None)
        if box is None:
            return
        txt = box.get("1.0", tk.END).strip()
        if not txt:
            messagebox.showwarning("ไม่มีข้อมูล", "ยังไม่มี Log ให้คัดลอก")
            return
        pyperclip.copy(txt)
        messagebox.showinfo("คัดลอกสำเร็จ", "คัดลอก Log ลงคลิปบอร์ดแล้ว")

